"""Row 5 table from the raw JSON-lines rows.

    python3 make_table.py --raw raw --out TABLE.md [--extra "Label=rows.jsonl" ...]

Every number is read from a row; nothing is typed in by hand. A cell that did not run shows its status. Only series whose
rows file exists are shown: raw/alloy_g4.jsonl, raw/mujoco_warp_g4.jsonl, raw/madrona_g4.jsonl, and any ``--extra`` file.
"""
from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path

from cam_scenes import OUTPUTS, SCENE_NAMES, SIZES, WORLDS

SCENES = SCENE_NAMES


@dataclass(frozen=True)
class Series:
    """One line of the table: an engine at one renderer setting."""
    label: str
    path: str
    key: str | None = None      # row field that selects the setting
    value: str | None = None    # substring that field must contain


SERIES = (
    Series("Alloy, 1 spp (Warp)", "alloy_g4.jsonl", "setting", "fast"),
    Series("Alloy, 1 spp (OptiX)", "alloy_g4.jsonl", "setting", "fast_optix"),
    Series("Alloy, 16 spp (camera default)", "alloy_g4.jsonl", "setting", "default"),
    Series("MuJoCo Warp renderer", "mujoco_warp_g4.jsonl"),
    Series("Madrona-MJX raytracer", "madrona_g4.jsonl", "renderer", "raytracer"),
    Series("Madrona-MJX rasterizer", "madrona_g4.jsonl", "renderer", "rasterizer"),
)


def load(series: Series, raw: Path) -> list[dict]:
    """Rows of one series (the file exists: see :func:`available`)."""
    rows = [json.loads(line) for line in (raw / series.path).read_text().splitlines() if line.startswith("{")]
    if series.key is None:
        return rows
    return [r for r in rows if _matches(r.get(series.key), series.value)]


def available(raw: Path, extra: dict[str, str]) -> tuple[Series, ...]:
    """The default series whose rows file exists, then the extra files (all their rows, under their label)."""
    found = tuple(s for s in SERIES if (raw / s.path).exists())
    return found + tuple(Series(label, str(Path(path).resolve())) for label, path in extra.items())


def _matches(field, value: str) -> bool:
    text = str(field or "")
    return text == value if value in ("fast", "default", "fast_optix") else value in text


def cell(rows: list[dict], scene: str, outputs: str, size: int, worlds: int) -> dict | None:
    """The newest row of one cell, or None."""
    hits = [r for r in rows if (r["scene"], r["outputs"], r["width"], r["worlds"]) == (scene, outputs, size, worlds)]
    return hits[-1] if hits else None


def fmt_rate(row: dict | None) -> str:
    if row is None:
        return "not measured"
    if row["status"] != "ok":
        return _status_text(row)
    return f"{row['images_per_s']:,.0f}"


def fmt_mem(row: dict | None) -> str:
    if row is None or row["status"] != "ok" or not row.get("gpu_mem_mib"):
        return "-"
    return f"{row['gpu_mem_mib'] / 1024:.1f}"


def _status_text(row: dict) -> str:
    reason = str(row.get("reason") or row.get("invalid_reason") or "")
    if row["status"] == "error" and "allocate" in reason:
        return "out of memory"
    return {"oom": "out of memory", "unsupported": "no such output", "error": "failed"}.get(row["status"], row["status"])


def headline(series: tuple[Series, ...], data: dict) -> list[str]:
    """128 px, 1,024 worlds: images/s and GiB for each engine, scene and output."""
    lines = ["| Engine | Scene | rgb | rgb + depth | rgb + depth + seg | GiB (rgb) |", "|---|---|---|---|---|---|"]
    for s in series:
        for scene in SCENES:
            cells = [cell(data[s.label], scene, o, 128, 1024) for o in OUTPUTS]
            lines.append(f"| {s.label} | {scene} | " + " | ".join(fmt_rate(c) for c in cells) + f" | {fmt_mem(cells[0])} |")
    return lines


def grid(series: tuple[Series, ...], data: dict, scene: str, outputs: str, fmt) -> list[str]:
    """Every size and world count for one scene and output."""
    head = " | ".join(f"{px} px, {w:,}" for px in SIZES for w in WORLDS)
    lines = [f"| Engine | {head} |", "|---|" + "---|" * 9]
    for s in series:
        vals = [fmt(cell(data[s.label], scene, outputs, px, w)) for px in SIZES for w in WORLDS]
        lines.append(f"| {s.label} | " + " | ".join(vals) + " |")
    return lines


def document(series: tuple[Series, ...], raw: Path) -> str:
    data = {s.label: load(s, raw) for s in series}
    out = ["# Row 5: camera throughput", "",
           "Generated by make_table.py from the raw rows; one RTX PRO 6000 Blackwell, physics on, one camera per world.",
           "", "## 128 px, 1,024 worlds: images/s", ""] + headline(series, data)
    for scene in SCENES:
        for outputs in OUTPUTS:
            out += ["", f"## {scene}, {outputs}: images/s (size, worlds)", ""] + grid(series, data, scene, outputs, fmt_rate)
        out += ["", f"## {scene}, rgb: peak GPU memory, GiB", ""] + grid(series, data, scene, "rgb", fmt_mem)
    return "\n".join(out) + "\n"


def parse_extra(items: list[str]) -> dict[str, str]:
    label_path = [i.partition("=") for i in items]
    if any(not sep for _, sep, _ in label_path):
        raise SystemExit('--extra takes "Label=rows.jsonl"')
    return {label: path for label, _, path in label_path}


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--raw", type=Path, default=Path("raw"))
    ap.add_argument("--out", type=Path, default=Path("TABLE.md"))
    ap.add_argument("--extra", action="append", default=[], metavar="LABEL=ROWS.jsonl")
    a = ap.parse_args(argv)
    series = available(a.raw, parse_extra(a.extra))
    a.out.write_text(document(series, a.raw))
    print(f"wrote {a.out}: {', '.join(s.label for s in series) or 'no series'}")


if __name__ == "__main__":
    main()
