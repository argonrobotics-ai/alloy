@wp.kernel
def _accumulate_window_force_kernel(
    ids: wp.array(dtype=int),
    world: wp.array(dtype=int),
    force: wp.array(dtype=wp.spatial_vector),
    counter: wp.array(dtype=int),
    k0: int,
    k1: int,
    h: float,
    out: wp.array2d(dtype=wp.float64),
):
    """Impulse of the coupler's interface force on the gripper bodies, per world, over outer steps [k0, k1)."""
    i = wp.tid()
    k = counter[0]
    if k < k0 or k >= k1:
        return
    f = wp.spatial_top(force[ids[i]])
    w = world[i]
    wp.atomic_add(out, w, 0, wp.float64(f[0] * h))
    wp.atomic_add(out, w, 1, wp.float64(f[1] * h))
    wp.atomic_add(out, w, 2, wp.float64(f[2] * h))


