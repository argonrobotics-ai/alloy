def _c05_rigid_boxes(builder: newton.ModelBuilder, kind: str) -> None:
    """Boxes of example_mujoco_vbd_coupled_solver.py:247-262 (masses) / example_mujoco_xpbd_coupled_solver.py
    (density)."""
    boxes = [(wp.vec3(0.0, 0.0, 2.0), (0.15, 0.15, 0.15), 10.0),
             (wp.vec3(0.3, 0.1, 2.5), (0.10, 0.20, 0.10), 5.0),
             (wp.vec3(-0.2, -0.1, 3.0), (0.12, 0.12, 0.12), 8.0)]
    saved = builder.default_shape_cfg.density
    if kind == "xpbd":
        builder.default_shape_cfg.density = 100.0
    for pos, (hx, hy, hz), mass in boxes:
        kw = {"mass": mass} if kind == "vbd" else {}
        body = builder.add_body(xform=wp.transform(p=pos, q=wp.quat_identity()), **kw)
        builder.add_shape_box(body, hx=hx, hy=hy, hz=hz)
    builder.default_shape_cfg.density = saved


def _c05_vbd_chain(builder: newton.ModelBuilder) -> None:
    """3-link pendulum anchored to the world (example_mujoco_vbd_coupled_solver.py:290-332)."""
    hx, hy, hz, damping = 0.21, 0.05, 0.05, 5.0
    anchor = wp.vec3(0.6, 0.0, 2.25)
    joints, parent = [], -1
    for k in range(3):
        link = builder.add_link()
        builder.add_shape_box(link, hx=hx, hy=hy, hz=hz)
        px = wp.transform(p=anchor if k == 0 else wp.vec3(hx, 0.0, 0.0), q=wp.quat_identity())
        joints.append(builder.add_joint_revolute(parent=parent, child=link, axis=wp.vec3(0.0, 1.0, 0.0),
                                                 target_kd=damping, parent_xform=px,
                                                 child_xform=wp.transform(p=wp.vec3(-hx, 0.0, 0.0),
                                                                          q=wp.quat_identity())))
        parent = link
    builder.add_articulation(joints, label="pendulum")


def _c05_xpbd_chain(builder: newton.ModelBuilder) -> None:
    """Free-falling 8-link chain (example_mujoco_xpbd_coupled_solver.py:296-325)."""
    n_links, hx, hy, hz, damping = 8, 0.06, 0.03, 0.03, 0.5
    saved = builder.default_shape_cfg.density
    builder.default_shape_cfg.density = 100.0
    prev = builder.add_link(xform=wp.transform(p=wp.vec3(-0.3, 0.0, 3.5), q=wp.quat_identity()))
    builder.add_shape_box(prev, hx=hx, hy=hy, hz=hz)
    joints = [builder.add_joint_free(child=prev)]
    for _ in range(n_links - 1):
        link = builder.add_link()
        builder.add_shape_box(link, hx=hx, hy=hy, hz=hz)
        joints.append(builder.add_joint_revolute(
            parent=prev, child=link, axis=wp.vec3(0.0, 1.0, 0.0), target_kd=damping,
            parent_xform=wp.transform(p=wp.vec3(hx, 0.0, 0.0), q=wp.quat_identity()),
            child_xform=wp.transform(p=wp.vec3(-hx, 0.0, 0.0), q=wp.quat_identity())))
        prev = link
    builder.add_articulation(joints, label="chain")
    builder.default_shape_cfg.density = saved


