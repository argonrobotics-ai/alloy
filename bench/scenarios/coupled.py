# z0: bed bottom. The example starts its bed at z = 0 with a jitter of one cell (offsets up to half a cell either way,
# builder.add_particle_grid), which puts particles below the floor at t = 0; the floor then pushes them up and the
# energy ledger records it as a gain. Lifted by one cell (2.5 cm).
C02_BED = dict(half=0.3, depth=0.2, voxel=0.05, ppc=2.0, density=2500.0, friction=0.75, z0=0.025)
C02_BOX_HALF = 0.08
C02_DROP_GAP = 0.10
C02_RHO_REF = 1000.0
C02_DENSITIES = (250.0, 1000.0, 2500.0, 4000.0)
C02_BOX_REST_S = 1.0  # the box hits the bed at ~0.14 s and has stopped sinking by 1 s: box-only energy ticks from here


def _c02_box_energy_set(boxes: Sequence[int], dt: float) -> dict:
    """Box-only energy sub-ledger over [C02_BOX_REST_S, end): separates coupling-fed gains of the rigid side from the
    MPM bed's own noise floor (the main ledger covers boxes + sand, or only the boxes for the explicit configs)."""
    return {"box": (np.asarray(boxes), None, (int(round(C02_BOX_REST_S / dt)), 1 << 30))}


def _c02_template(*, sand: bool, box: bool, kamino: bool) -> tuple[newton.ModelBuilder, list[int]]:
    b = newton.ModelBuilder()
    b.default_shape_cfg.mu = 0.5
    if kamino:
        SolverKamino.register_custom_attributes(b)
    if sand:
        SolverImplicitMPM.register_custom_attributes(b)
    if box:
        h = C02_BOX_HALF
        body = b.add_body(xform=wp.transform(p=wp.vec3(0.0, 0.0, C02_BED["z0"] + C02_BED["depth"] + h + C02_DROP_GAP),
                                             q=wp.quat_identity()), mass=C02_RHO_REF * (2 * h) ** 3)
        b.add_shape_box(body, hx=h, hy=h, hz=h)
    sand_ids = []
    if sand:
        c = C02_BED
        sand_ids = _add_sand_block(b, (-c["half"], -c["half"], c["z0"]), (c["half"], c["half"], c["z0"] + c["depth"]),
                                   c["voxel"],
                                   c["ppc"], c["density"], {"mpm:friction": c["friction"]})
    return b, sand_ids


def _c02_set_densities(model, nworld: int, bodies_per_world: int) -> np.ndarray:
    """World w gets box density C02_DENSITIES[w % 4] (scaled from the template's 1000 kg/m^3)."""
    dens = np.array([C02_DENSITIES[w % len(C02_DENSITIES)] for w in range(nworld)])
    mass = model.body_mass.numpy()
    for w in range(nworld):
        ids = np.arange(w * bodies_per_world, (w + 1) * bodies_per_world)
        if dens[w] != C02_RHO_REF:
            _scale_body_mass(model, ids, dens[w] / C02_RHO_REF)
    del mass
    return dens


def _c02_proxy(nworld: int, device: str, config: Config) -> Built:
    """Rigid boxes (MuJoCo or Kamino) as proxy colliders inside implicit MPM, harvested MPM wrenches fed back.

    Derived from newton/examples/multiphysics/example_mujoco_mpm_coupled_solver.py. The rigid entry runs
    `ratio` substeps per MPM step (the multi-rate axis). Bed 0.6 x 0.6 x 0.2 m (example: 2 x 2 x 0.5 m), 2 ppc
    (example: 3) so the Mac smoke test runs; one 16 cm box per world (example: six 75 kg boxes).
    """
    p = config.params
    kamino = p["rigid"] == "kamino"
    tpl, _ = _c02_template(sand=True, box=True, kamino=kamino)
    nb, npw = tpl.body_count, tpl.particle_count
    main = _replicate(tpl, nworld)
    if kamino:
        SolverKamino.register_custom_attributes(main)
    SolverImplicitMPM.register_custom_attributes(main)
    main.add_ground_plane()
    model = main.finalize(device=device)
    dens = _c02_set_densities(model, nworld, nb)
    mpm_cfg = _mpm_config(C02_BED["voxel"], nworld, iterations=p.get("mpm_iterations", 50))
    rname, rfactory = _rigid_entry(p["rigid"], {"use_mujoco_contacts": False, "njmax": 100 * nworld})
    boxes = list(range(model.body_count))
    solver = SolverCoupledProxy(
        model=model,
        entries=[SolverCoupledProxy.Entry(name=rname, solver=rfactory, bodies=boxes,
                                          joints=list(range(model.joint_count)), substeps=p["ratio"]),
                 SolverCoupledProxy.Entry(name="mpm", solver=lambda v: SolverImplicitMPM(model=v, config=mpm_cfg),
                                          particles=list(range(model.particle_count)), in_place=True)],
        coupling=SolverCoupledProxy.Config(
            proxies=[SolverCoupledProxy.Proxy(source=rname, destination="mpm", bodies=boxes,
                                              mass_scale=p.get("mass_scale", 1.0), mode="lagged",
                                              collision_pipeline=lambda _m: None)],
            iterations=p.get("proxy_iterations", 1)))
    s0 = model.state()
    pipeline = newton.CollisionPipeline(model, soft_contact_max=0)
    contacts = pipeline.contacts()
    control = model.control()
    newton.eval_fk(model, model.joint_q, model.joint_qd, s0)
    mpm = solver.solver("mpm")
    ledger = _StaticImpulseLedger(mpm, lambda: [solver.entry_state("mpm", "input"),
                                                solver.entry_state("mpm", "output")], device)
    return Built(model, solver, s0, s0, control, contacts, pipeline, nworld=nworld,
                 extra={"in_place": True, "boxes": np.asarray(boxes), "sand": np.arange(model.particle_count),
                        "densities": dens, "ledger": ledger, "npw": npw,
                        "energy_sets": _c02_box_energy_set(boxes, config.dt),
                        "post_substep": _c02_post_substep,
                        "box_impulse": _ImpulseIntegrator(lambda: _proxy_force_array(solver, "body"),
                                                          np.asarray(boxes), device)})


def _c02_post_substep(b: Built, dt: float) -> None:
    b.extra["ledger"].accumulate()
    b.extra["box_impulse"].accumulate(dt)


def _c02_explicit(nworld: int, device: str, config: Config) -> Built:
    """Hand-rolled explicit coupling: MPM sees the boxes as colliders; sand impulses are (optionally) applied back.

    Derived from newton/examples/mpm/example_mpm_twoway_coupling.py (two models, impulses lagged one frame).
    params: feedback (True = two-way baseline, False = one-way: the boxes never feel the sand).
    """
    p = config.params
    rtpl, _ = _c02_template(sand=False, box=True, kamino=False)
    stpl, _ = _c02_template(sand=True, box=False, kamino=False)
    nb = rtpl.body_count
    rmain = _replicate(rtpl, nworld)
    rmain.add_ground_plane()
    smain = _replicate(stpl, nworld)
    SolverImplicitMPM.register_custom_attributes(smain)
    model = rmain.finalize(device=device)
    sand_model = smain.finalize(device=device)
    dens = _c02_set_densities(model, nworld, nb)
    mpm = SolverImplicitMPM(sand_model, config=_mpm_config(C02_BED["voxel"], nworld,
                                                           iterations=p.get("mpm_iterations", 50)))
    mpm.setup_collider(model=model)
    solver = SolverMuJoCo(model, use_mujoco_contacts=False, njmax=100 * nworld)
    s0, s1, control = model.state(), model.state(), model.control()
    sand_state = sand_model.state()
    sand_state.body_q = wp.empty_like(s0.body_q)
    sand_state.body_qd = wp.empty_like(s0.body_qd)
    sand_state.body_f = wp.empty_like(s0.body_f)
    pipeline = newton.CollisionPipeline(model)
    contacts = pipeline.contacts()
    newton.eval_fk(model, model.joint_q, model.joint_qd, s0)
    max_nodes = 1 << 20
    ex = {"mpm": mpm, "sand_model": sand_model, "sand_state": sand_state, "feedback": bool(p["feedback"]),
          "ratio": int(p["ratio"]), "imp": wp.zeros(max_nodes, dtype=wp.vec3, device=device),
          "imp_pos": wp.zeros(max_nodes, dtype=wp.vec3, device=device),
          "imp_ids": wp.full(max_nodes, value=-1, dtype=int, device=device),
          "sand_f": wp.zeros_like(s0.body_f), "boxes": np.arange(model.body_count), "densities": dens,
          "energy_sets": _c02_box_energy_set(np.arange(model.body_count), config.dt)}
    ex["ledger"] = _StaticImpulseLedger(mpm, lambda: [sand_state], device)
    ex["custom_substep"] = _c02_explicit_substep
    ex["box_impulse"] = _ImpulseIntegrator(lambda: ex["sand_f"], np.arange(model.body_count), device)
    b = Built(model, solver, s0, s1, control, contacts, pipeline, nworld=nworld, extra=ex)
    _c02_collect_impulses(b)
    return b


def _c02_collect_impulses(b: Built) -> None:
    ex = b.extra
    imp, pos, ids = ex["mpm"].collect_collider_impulses(ex["sand_state"])
    ex["imp_ids"].fill_(-1)
    n = min(imp.shape[0], ex["imp"].shape[0])
    ex["imp"][:n].assign(imp[:n])
    ex["imp_pos"][:n].assign(pos[:n])
    ex["imp_ids"][:n].assign(ids[:n])


def _c02_explicit_substep(b: Built, frame_dt: float) -> None:
    """One frame of example_mpm_twoway_coupling.py:simulate (rigid substeps, then one sand step)."""
    ex, model, dev = b.extra, b.model, b.model.device
    h = frame_dt / ex["ratio"]
    for _ in range(ex["ratio"]):
        b.state_0.clear_forces()
        if ex["feedback"]:
            wp.launch(_sand_body_forces_kernel, dim=ex["imp_ids"].shape[0], device=dev,
                      inputs=[frame_dt, ex["imp_ids"], ex["imp"], ex["imp_pos"], ex["mpm"].collider_body_index,
                              b.state_0.body_q, model.body_com, b.state_0.body_f])
            ex["sand_f"].assign(b.state_0.body_f)
        b.pipeline.collide(b.state_0, b.contacts)
        b.solver.step(b.state_0, b.state_1, b.control, b.contacts, h)
        b.state_0, b.state_1 = b.state_1, b.state_0
    ss = ex["sand_state"]
    if ex["feedback"]:
        wp.launch(_subtract_body_force_kernel, dim=ss.body_q.shape[0], device=dev,
                  inputs=[frame_dt, b.state_0.body_q, b.state_0.body_qd, ex["sand_f"], model.body_inv_inertia,
                          model.body_inv_mass, ss.body_q, ss.body_qd])
    else:
        wp.copy(ss.body_q, b.state_0.body_q)
        wp.copy(ss.body_qd, b.state_0.body_qd)
        _sand_wrench_only(b, frame_dt)
    # sand_f = the wrench the boxes felt this frame (computed but not applied in the one-way run)
    ex["box_impulse"].accumulate(frame_dt)
    ex["mpm"].step(ss, ss, contacts=None, control=None, dt=frame_dt)
    _c02_collect_impulses(b)
    ex["ledger"].accumulate()


def _sand_wrench_only(b: Built, frame_dt: float) -> None:
    """One-way run: still compute the sand wrench (for the force-balance metric) but never apply it."""
    ex = b.extra
    ex["sand_f"].zero_()
    wp.launch(_sand_body_forces_kernel, dim=ex["imp_ids"].shape[0], device=b.model.device,
              inputs=[frame_dt, ex["imp_ids"], ex["imp"], ex["imp_pos"], ex["mpm"].collider_body_index,
                      b.state_0.body_q, b.model.body_com, ex["sand_f"]])


class RigidSand(_CoupledScenario):
    """C02: rest wrench = m g within 2 %, momentum ledger within 1 %, no energy gain."""

    id = "C02_rigid_sand"
    title = "Rigid boxes (density sweep) dropped into a granular implicit-MPM bed; MPM:rigid dt ratio 1/2/4"
    horizon_s = 2.0
    has_contacts = True
    accuracy_unit = "%"
    accuracy_ref = "max over boxes |F_sand,z - m g| / (m g), mean over the last 0.5 s (rest wrench)"
    ladder = (1, 16, 256, 1024)
    sample_every = 5
    rest_window_s = 0.5
    _F = 1.0 / 100.0  # example fps 100
    configs = (
        Config("proxy_mujoco_r1", "proxy:mujoco+mpm", dt=_F, params={"rigid": "mujoco", "ratio": 1}, max_nworld=256),
        Config("proxy_mujoco_r2", "proxy:mujoco+mpm", dt=_F, params={"rigid": "mujoco", "ratio": 2}, max_nworld=256),
        Config("proxy_mujoco_r4", "proxy:mujoco+mpm", dt=_F, params={"rigid": "mujoco", "ratio": 4}, max_nworld=256),
        Config("proxy_kamino_r4", "proxy:kamino+mpm", dt=_F, params={"rigid": "kamino", "ratio": 4}, max_nworld=256),
        Config("explicit_twoway_mujoco_r4", "explicit:mujoco+mpm", dt=_F, params={"feedback": True, "ratio": 4},
               max_nworld=256),
        Config("oneway_mujoco_r4", "oneway:mujoco+mpm", dt=_F, params={"feedback": False, "ratio": 4},
               max_nworld=256),
    )

    def _scene(self, nworld: int, device: str, config: Config) -> Built:
        if "rigid" in config.params:
            return _c02_proxy(nworld, device, config)
        return _c02_explicit(nworld, device, config)

    def substep(self, b: Built, dt: float) -> None:
        custom = b.extra.get("custom_substep")
        if custom is None:
            super().substep(b, dt)
        else:
            custom(b, dt)

    def state_arrays(self, b: Built) -> dict[str, np.ndarray]:
        out = super().state_arrays(b)
        ss = b.extra.get("sand_state")
        if ss is not None:
            out["sand_particle_q"] = ss.particle_q.numpy()
        return out

    def energy(self, b: Built) -> float | None:
        e = M.rigid_energy(b.model, b.state_0)
        ss = b.extra.get("sand_state")
        return e + (M.particle_energy(b.extra["sand_model"], ss) if ss is not None else
                    M.particle_energy(b.model, b.state_0))

    def _snapshot(self, b: Built) -> tuple[np.ndarray, float]:
        """(total momentum, total mass) over boxes and sand, whichever model holds the sand."""
        model = b.model
        body_qd = b.state_0.body_qd.numpy().astype(np.float64)
        p = _momentum(model, None, body_qd, None, b.extra["boxes"], None)
        mass = float(model.body_mass.numpy()[b.extra["boxes"]].sum())
        ss = b.extra.get("sand_state")
        smodel, sstate = (b.extra["sand_model"], ss) if ss is not None else (model, b.state_0)
        pm = smodel.particle_mass.numpy().astype(np.float64)
        p += (pm[:, None] * sstate.particle_qd.numpy().astype(np.float64)).sum(axis=0)
        return p, mass + float(pm.sum())

    def on_start(self, b: Built, rec: dict) -> None:
        p0, mass = self._snapshot(b)
        b.extra.update(p0=p0, mass_total=mass, t0=self.sim_time(b), j0=b.extra["ledger"].value(), fz=[], jz=[],
                       floor_touch=False)

    def measure(self, b: Built, t: float, rec: dict) -> None:
        super().measure(b, t, rec)
        boxes = b.extra["boxes"]
        if b.extra["box_impulse"].available:
            b.extra["fz"].append((t, b.extra["box_impulse"].value()[:, 2]))
        b.extra["jz"].append((t, b.extra["ledger"].value()))
        q = b.state_0.body_q.numpy()
        b.extra["box_z"] = q[boxes, 2].astype(np.float64)
        if np.any(q[boxes, 2] - C02_BOX_HALF * np.sqrt(3.0) < 0.002):
            b.extra["floor_touch"] = True  # a box corner may reach the floor: its ground impulse is not ledgered

    def finish(self, b: Built, rec: dict) -> None:
        super().finish(b, rec)
        model, boxes = b.model, b.extra["boxes"]
        g = _gravity(model)
        gn = float(np.linalg.norm(g))
        mg = model.body_mass.numpy()[boxes].astype(np.float64) * gn
        t_end = self.sim_time(b)
        fz = _mean_force(b.extra["fz"], t_end - self.rest_window_s, t_end)
        if fz is None:
            fz = np.full(len(boxes), np.nan)
        err = np.abs(fz - mg) / mg * 100.0
        p1, mass = self._snapshot(b)
        j = b.extra["ledger"].value() - b.extra["j0"]
        T = t_end - b.extra["t0"]
        ledger = _ledger_residual(b.extra["p0"], p1, j, mass, g, T, float(mg.sum() / gn))
        jwin = _window(b.extra["jz"], t_end - self.rest_window_s, t_end)
        floor_support = None
        if len(jwin) >= 2:
            dj = (jwin[-1][1][2] - jwin[0][1][2]) / max(jwin[-1][0] - jwin[0][0], 1e-12)
            floor_support = abs(dj - mass * gn) / (mass * gn) * 100.0
        sink = (C02_BED["z0"] + C02_BED["depth"] - (b.extra["box_z"] - C02_BOX_HALF)) * 1e3
        dens = b.extra["densities"]
        per_cond = {str(int(d)): {"force_balance_err_pct": _finite_or_none(float(np.nanmax(err[dens == d]))),
                                  "sink_depth_mm": float(np.max(sink[dens == d]))} for d in np.unique(dens)}
        m = rec["metrics"]
        acc = _finite_or_none(float(np.nanmax(err)))
        m.update(force_balance_err_pct=acc, sink_depth_mm=float(np.max(sink)), floor_support_err_pct=floor_support,
                 per_condition=per_cond, conditions_covered=b.nworld >= len(C02_DENSITIES),
                 ledger_floor_contact_rigid=b.extra["floor_touch"], **ledger,
                 law_pass=bool(acc is not None and acc <= 2.0 and ledger["momentum_residual_pct"] <= 1.0
                               and not b.extra["floor_touch"] and m["energy_ok"]))
        rec["accuracy_error"] = acc


