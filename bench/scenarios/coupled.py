def _c01_keyframes(variant: str, start_tcp: np.ndarray | None) -> tuple[np.ndarray, np.ndarray, dict]:
    """Keyframe table [px, py, pz, qx, qy, qz, qw, finger] and cumulative end times, plus named phase windows.

    The examples' sequences with one change: a C01_HOLD_S static hold after the lift, so the hold law has a window
    where the arm does no work on the payload.
    """
    v = C01_VARIANTS[variant]
    cx, cy, cz = v["center"]
    up, down = cz + 0.20, cz
    tx, ty = C01_PLACE_XY
    q = list(C01_GRIPPER_DOWN)
    o, c = C01_GRIP_OPEN, C01_GRIP_CLOSED
    rows: list[tuple[str, float, list[float]]] = []
    if v["start_move_s"] is not None:
        rows.append(("start", v["start_move_s"], [*start_tcp.tolist(), o]))
    rows += [("approach", 1.0 if variant == "proxy" else 0.5, [cx, cy, up, *q, o]),
             ("descend", 0.5, [cx, cy, down, *q, o]),
             ("grasp", 1.0, [cx, cy, down, *q, c]),
             ("lift", 1.0, [cx, cy, up, *q, c]),
             ("hold", C01_HOLD_S, [cx, cy, up, *q, c]),
             ("carry", 1.0, [tx, ty, up, *q, c]),
             ("lower", 0.5, [tx, ty, down, *q, c]),
             ("settle", 0.5, [tx, ty, down, *q, c]),
             ("release", 1.0, [tx, ty, down, *q, o]),
             ("retract", 0.5, [tx, ty, up, *q, o])]
    targets = np.asarray([r[2] for r in rows], dtype=np.float32)
    ends = np.cumsum([r[1] for r in rows])
    phases = {name: (float(ends[i - 1]) if i else 0.0, float(ends[i])) for i, (name, _, _) in enumerate(rows)}
    return targets, ends, phases


def _c01_interp(targets: np.ndarray, ends: np.ndarray, t: float) -> np.ndarray:
    """Linear keyframe interpolation, identical to the examples' update_ik_targets."""
    t = min(t, float(ends[-1]) - 1e-6)
    k = int(np.searchsorted(ends, t))
    t0 = ends[k - 1] if k > 0 else 0.0
    a = float(np.clip((t - t0) / max(ends[k] - t0, 1e-6), 0.0, 1.0))
    prev = targets[k - 1] if k > 0 else targets[k]
    return (1.0 - a) * prev + a * targets[k]


def _c01_ik_model(variant: str, device: str):
    v = C01_VARIANTS[variant]
    b = newton.ModelBuilder(gravity=(0.0, 0.0, -9.81))
    _c01_add_franka(b, v["center"][2] - v["radius"], v["franka_q"])
    return b.finalize(device=device)


def _c01_start_tcp(ik_model) -> np.ndarray:
    state = ik_model.state()
    newton.eval_fk(ik_model, ik_model.joint_q, ik_model.joint_qd, state)
    hq = state.body_q.numpy()[_label_index(ik_model.body_label, "fr3_hand")].astype(np.float64)
    tcp = hq[:3] + M.quat_rotate(hq[3:7], np.array([0.0, 0.0, C01_TCP_OFFSET]))
    return np.concatenate([tcp, hq[3:7]]).astype(np.float32)


@lru_cache(maxsize=8)
def _c01_joint_targets(variant: str, device: str, frame_dt: float, n_frames: int) -> np.ndarray:
    """Per-frame joint targets (7 arm + 2 fingers), precomputed with Newton's IK exactly as the examples run it.

    The examples solve IK every frame (24 LM iterations, warm-started from the previous IK solution, never from the
    simulated arm), so the target sequence depends only on the keyframes. Solving it once at build time and replaying
    it from a device table indexed by the step counter gives the same targets and keeps step() graph-capturable.
    """
    import alloy._vendor.newton.ik as ik

    ik_model = _c01_ik_model(variant, device)
    n = ik_model.joint_coord_count
    targets, ends, _ = _c01_keyframes(variant, _c01_start_tcp(ik_model))
    q = wp.array(np.asarray(C01_VARIANTS[variant]["franka_q"], np.float32).reshape(1, n), dtype=wp.float32,
                 device=device)
    pos = wp.array(targets[:1, :3], dtype=wp.vec3, device=device)
    rot = wp.array(targets[:1, 3:7], dtype=wp.vec4, device=device)
    hand = _label_index(ik_model.body_label, "fr3_hand")
    objectives = [
        ik.IKObjectivePosition(link_index=hand, link_offset=wp.vec3(0.0, 0.0, C01_TCP_OFFSET), target_positions=pos),
        ik.IKObjectiveRotation(link_index=hand, link_offset_rotation=wp.quat_identity(), target_rotations=rot),
        ik.IKObjectiveJointLimit(joint_limit_lower=wp.clone(ik_model.joint_limit_lower),
                                 joint_limit_upper=wp.clone(ik_model.joint_limit_upper), weight=10.0)]
    solver = ik.IKSolver(model=ik_model, n_problems=1, objectives=objectives, lambda_initial=0.05,
                         jacobian_mode=ik.IKJacobianType.ANALYTIC)
    rows = np.zeros((n_frames, n), dtype=np.float32)
    for k in range(n_frames):
        tgt = _c01_interp(targets, ends, k * frame_dt)
        pos.assign(tgt[None, :3])
        rot.assign(tgt[None, 3:7])
        solver.step(q, q, iterations=C01_IK_ITERS)
        qn = q.numpy()
        qn[0, n - 2:] = tgt[-1]  # set_gripper_q: finger width written into the IK warm start
        q.assign(qn)
        rows[k] = qn[0]
    return rows


def _c01_emit_payload(b: newton.ModelBuilder, variant: str, payload: str) -> None:
    """VBD rod (proxy example: soft IsaacLab cable; ADMM example: stiff cable) or the ADMM example's XPBD chain."""
    v = C01_VARIANTS[variant]
    center, length, r, nseg = wp.vec3(*v["center"]), v["length"], v["radius"], v["segments"]
    if payload == "xpbd_chain":  # example_mujoco_franka_vbd_cable_admm_solver.py:_emit_xpbd_chain
        seg = length / nseg
        start = center - wp.vec3(0.5 * length, 0.0, -0.002)
        cfg = newton.ModelBuilder.ShapeConfig(density=900.0, ke=6.0e4, kd=1.5e1, mu=0.9, margin=0.001, gap=0.002)
        xf = wp.transform(p=wp.vec3(0.0), q=wp.quat_from_axis_angle(wp.vec3(0.0, 1.0, 0.0), 0.5 * wp.pi))
        bodies, joints = [], []
        for s in range(nseg):
            body = b.add_link(xform=wp.transform(p=start + wp.vec3((s + 0.5) * seg, 0.0, 0.0), q=wp.quat_identity()))
            b.add_shape_capsule(body, xform=xf, radius=r, half_height=max(0.25 * r, 0.5 * seg - r), cfg=cfg)
            bodies.append(body)
            if s == 0:
                joints.append(b.add_joint_free(child=body))
                continue
            joints.append(b.add_joint_ball(
                parent=bodies[s - 1], child=body, friction=0.02, collision_filter_parent=True,
                parent_xform=wp.transform(p=wp.vec3(0.5 * seg, 0.0, 0.0), q=wp.quat_identity()),
                child_xform=wp.transform(p=wp.vec3(-0.5 * seg, 0.0, 0.0), q=wp.quat_identity())))
        b.add_articulation(joints, label="xpbd_chain")
        return
    rod = newton.Rod.create_straight(start=center - wp.vec3(0.5 * length, 0.0, 0.0), direction=wp.vec3(1.0, 0.0, 0.0),
                                     length=length, segment_count=nseg, twist_total=0.0, radius=r)
    if variant == "proxy":  # example_franka_cable_ik_pick_place.py:_emit_template
        cfg = newton.ModelBuilder.ShapeConfig(density=100.0, ke=1.0e3, kd=1.0e-1, mu=1.0, margin=0.0, gap=0.01)
        b.add_rod(rod=rod, cfg=cfg, stretch_stiffness=1.0e2, stretch_damping=1.0e-1, bend_stiffness=4.0e-4,
                  bend_damping=2.0e-3 * 4.0e-4, label="vbd_cable")
    else:  # example_mujoco_franka_vbd_cable_admm_solver.py:_emit_vbd_cable
        cfg = newton.ModelBuilder.ShapeConfig(density=1400.0, ke=5.0e4, kd=1.0e1, mu=0.9, margin=0.001, gap=0.002)
        b.add_rod(rod=rod, body_frame_origin="start", cfg=cfg, stretch_stiffness=2.0e5, stretch_damping=2.0e-2,
                  bend_stiffness=0.08, bend_damping=2.0e-2 * 0.08, label="vbd_cable")


def _c01_template(variant: str, payload: str) -> tuple[newton.ModelBuilder, dict]:
    v = C01_VARIANTS[variant]
    tpl = newton.ModelBuilder(gravity=(0.0, 0.0, -9.81))
    tpl.rigid_gap = v["rigid_gap"]
    SolverMuJoCo.register_custom_attributes(tpl)
    if payload == "vbd_cable":
        SolverVBD.register_custom_attributes(tpl)
    _c01_add_franka(tpl, v["center"][2] - v["radius"], v["franka_q"])
    tpl.joint_target_ke[:7] = [v["arm_ke"]] * 7
    tpl.joint_target_kd[:7] = [v["arm_kd"]] * 7
    tpl.joint_target_ke[7:9] = [1000.0, 1000.0]
    tpl.joint_target_kd[7:9] = [100.0, 100.0]
    tpl.joint_effort_limit[:7] = v["effort"]
    tpl.joint_effort_limit[7:9] = [v["grip_force"]] * 2
    tpl.joint_armature[:7] = [v["armature"]] * 7
    tpl.joint_armature[7:9] = [0.0, 0.0]
    franka = list(range(tpl.body_count))
    franka_joints, franka_shapes = list(range(tpl.joint_count)), list(range(tpl.shape_count))
    gravcomp = tpl.custom_attributes["mujoco:gravcomp"]
    if gravcomp.values is None:
        gravcomp.values = {}
    for body in franka:  # full gravity compensation on the arm (both examples)
        gravcomp.values[body] = 1.0
    gripper = [i for i in franka if "hand" in tpl.body_label[i] or "finger" in tpl.body_label[i]]
    if variant == "proxy":  # gripper contact material matched to the cable (proxy example)
        for s, body in enumerate(tpl.shape_body):
            if body in gripper:
                tpl.shape_material_ke[s], tpl.shape_material_kd[s], tpl.shape_material_mu[s] = 1.0e3, 1.0e-1, 1.0
    b0, j0, s0 = tpl.body_count, tpl.joint_count, tpl.shape_count
    _c01_emit_payload(tpl, variant, payload)
    ids = {"franka": franka, "franka_joints": franka_joints, "franka_shapes": franka_shapes, "gripper": gripper,
           "hand": _label_index(tpl.body_label, "fr3_hand"), "payload": list(range(b0, tpl.body_count)),
           "payload_joints": list(range(j0, tpl.joint_count)), "payload_shapes": list(range(s0, tpl.shape_count))}
    return tpl, ids


def _c01_solver(model, config: Config, ids: dict, nworld: int):
    p = config.params
    mj = dict(solver="newton", integrator="implicitfast", iterations=p["mujoco_iterations"],
              ls_iterations=p["mujoco_ls_iterations"], use_mujoco_contacts=False, njmax=max(256, 64 * nworld),
              nconmax=max(64, 16 * nworld))
    if config.solver.startswith("proxy"):
        mj["cone"] = "elliptic"
        vbd_it = p["vbd_iterations"]
        return SolverCoupledProxy(
            model=model,
            entries=[SolverCoupled.Entry(name="mjc", solver=lambda v: SolverMuJoCo(model=v, **mj), bodies=ids["franka"],
                                         joints=ids["franka_joints"]),
                     SolverCoupled.Entry(name="vbd", solver=lambda v: SolverVBD(model=v, iterations=vbd_it,
                                                                                rigid_contact_history=False),
                                         bodies=ids["payload"], joints=ids["payload_joints"])],
            coupling=SolverCoupledProxy.Config(
                proxies=[SolverCoupledProxy.Proxy(
                    source="mjc", destination="vbd", bodies=ids["gripper"], mass_scale=p.get("mass_scale", 1.0),
                    mode=p.get("coupling_mode", "lagged"), collide_interval=1,
                    collision_pipeline=lambda m: newton.CollisionPipeline(m, broad_phase="explicit"))],
                iterations=p.get("proxy_iterations", 1)))
    if p["payload"] == "vbd_cable":
        name, vbd_it = "vbd", p["vbd_iterations"]
        factory = lambda v: SolverVBD(model=v, iterations=vbd_it, rigid_contact_history=False)  # noqa: E731
    else:
        name = "xpbd"
        xkw = dict(iterations=p["xpbd_iterations"], joint_linear_relaxation=p.get("xpbd_joint_linear_relaxation", 0.9),
                   joint_angular_relaxation=p.get("xpbd_joint_angular_relaxation", 0.5), angular_damping=0.02)
        factory = lambda v: SolverXPBD(model=v, **xkw)  # noqa: E731
    return SolverCoupledADMM(
        model=model,
        entries=[SolverCoupled.Entry(name="mjc", solver=lambda v: SolverMuJoCo(model=v, **mj), bodies=ids["franka"],
                                     joints=ids["franka_joints"]),
                 SolverCoupled.Entry(name=name, solver=factory, bodies=ids["payload"], joints=ids["payload_joints"])],
        coupling=SolverCoupledADMM.Config(
            iterations=p.get("admm_iterations", 5), rho=p.get("rho", 200.0), gamma=p.get("gamma", 0.001),
            baumgarte=p.get("baumgarte", 0.5), rigid_contact_matching=p.get("rigid_contact_matching", "latest"),
            contact_matching_force_scale=p.get("contact_matching_force_scale", 0.9),
            contact_pairs=[SolverCoupledADMM.ContactPair(source="mjc", destination=name)]))


def _c01_interface_force_source(b: Built, bodies: np.ndarray) -> tuple[wp.array, np.ndarray] | None:
    """(force array, index of each given arm body in it): the interface force the coupler applies to the arm.

    Proxy: SolverCoupledProxy._proxy_mappings[0].coupling_forces, global body ids (private; the harvested lagged
    feedback that is added to MuJoCo's body_f, solver_coupled_proxy.py:_step_proxy). ADMM:
    SolverCoupledADMM._admm_buffers["mjc"].body_f, mjc-local ids (private; external body_f plus the ADMM contact
    forces of the last iteration, solver_coupled_admm.py:3841-3889). Both are allocated once, so graph-safe.
    """
    maps = getattr(b.solver, "_proxy_mappings", None)
    if maps:
        arr = maps[0].coupling_forces
        return (arr, bodies) if int(np.max(bodies)) < arr.shape[0] else None
    bufs, entries = getattr(b.solver, "_admm_buffers", None), getattr(b.solver, "_entries", None)
    if not bufs or "mjc" not in bufs or bufs["mjc"].body_f is None:
        return None
    local = entries["mjc"].body_global_to_local.numpy()[bodies]
    return (bufs["mjc"].body_f, local) if np.all(local >= 0) else None


def _c01_scene(nworld: int, device: str, config: Config) -> Built:
    """Franka FR3 (MuJoCo Warp) picks a cable at its middle, lifts, holds, carries and places it.

    Derived from newton/examples/multiphysics/example_franka_cable_ik_pick_place.py (proxy: MuJoCo + VBD rod) and
    example_mujoco_franka_vbd_cable_admm_solver.py (ADMM: MuJoCo + VBD rod or XPBD rigid chain). Robot, payload,
    gains, contact and coupler settings are the examples' defaults; the joint-target sequence is the examples' IK
    run, precomputed (see _c01_joint_targets). params: variant (proxy | admm), payload (vbd_cable | xpbd_chain).
    """
    p = config.params
    variant, payload = p["variant"], p["payload"]
    v = C01_VARIANTS[variant]
    surface_z = v["center"][2] - v["radius"]
    tpl, ids = _c01_template(variant, payload)
    nb, nj, ns = tpl.body_count, tpl.joint_count, tpl.shape_count
    main = _replicate(tpl, nworld, gravity=(0.0, 0.0, -9.81))
    ex = {k: _expand(ids[k], stride, nworld) for k, stride in
          (("franka", nb), ("gripper", nb), ("payload", nb), ("franka_joints", nj), ("payload_joints", nj),
           ("franka_shapes", ns), ("payload_shapes", ns))}
    plane = (dict(ke=1.0e3, kd=1.0e-1, mu=1.0, margin=0.0, gap=0.01) if variant == "proxy"
             else dict(ke=8.0e4, kd=2.0e1, mu=0.8, margin=0.001, gap=0.002))
    ground = main.add_ground_plane(height=surface_z, cfg=newton.ModelBuilder.ShapeConfig(**plane))
    main.color()
    model = main.finalize(device=device)
    sids = {"franka": ex["franka"], "franka_joints": ex["franka_joints"], "gripper": ex["gripper"],
            "payload": ex["payload"], "payload_joints": ex["payload_joints"]}
    solver = _c01_solver(model, config, sids, nworld)
    s0, s1, control = model.state(), model.state(), model.control()
    if variant == "proxy":  # robot/cable vs ground only; gripper-cable contact lives in the proxy's own pipeline
        dyn = set(ex["franka_shapes"]) | set(ex["payload_shapes"])
        pairs = [(int(a), int(c)) for a, c in model.shape_contact_pairs.numpy() if ({int(a), int(c)} & dyn)
                 and ground in (int(a), int(c))]
        pipeline = newton.CollisionPipeline(model, broad_phase="explicit", shape_pairs_filtered=wp.array(
            np.asarray(pairs, dtype=np.int32), dtype=wp.vec2i, device=device))
    else:
        pipeline = newton.CollisionPipeline(model)
    contacts = pipeline.contacts()
    solver.prepare_contacts(contacts)
    newton.eval_fk(model, model.joint_q, model.joint_qd, s0)
    newton.eval_fk(model, model.joint_q, model.joint_qd, s1)

    n_frames = int(round(RigidCablePickPlace.horizon_s / config.dt)) + 2
    rows = _c01_joint_targets(variant, str(device), float(config.dt), n_frames)
    table = wp.array(rows, dtype=float, device=device)
    stride = control.joint_target_q.shape[0] // nworld
    ncoord = rows.shape[1]

    def pre_step(b: Built) -> None:
        wp.launch(_apply_target_row_kernel, dim=(nworld, ncoord), device=device,
                  inputs=[table, b.extra["counter"], stride, b.control.joint_target_q])

    _, _, phases = _c01_keyframes(variant, _c01_start_tcp(_c01_ik_model(variant, device)))
    k0 = int(round((phases["hold"][0] + C01_HOLD_SETTLE_S) / config.dt))
    k1 = int(round(phases["hold"][1] / config.dt))
    gripper_all = np.asarray(ex["gripper"])
    mid = ids["payload"][len(ids["payload"]) // 2] - ids["payload"][0]
    extra = {"eval_ik": True, "pre_step": pre_step, "phases": phases, "hold_k": (k0, k1), "energy_window": (k0, k1),
             "energy_bodies": np.asarray(ex["payload"]), "energy_law": "tick", "gripper_all": gripper_all,
             "arm_all": np.asarray(ex["franka"]), "payload_all": np.asarray(ex["payload"]),
             "payload_n": len(ids["payload"]), "mid": mid, "hand_all": np.asarray(_expand([ids["hand"]], nb, nworld)),
             "surface_z": surface_z, "radius": v["radius"], "center": np.asarray(v["center"]),
             "impulse": wp.zeros((nworld, 3), dtype=wp.float64, device=device),
             "impulse_arm": wp.zeros((nworld, 3), dtype=wp.float64, device=device)}
    extra["post_substep"] = _c01_post_substep
    return Built(model, solver, s0, s1, control, contacts, pipeline, nworld=nworld, extra=extra)


def _c01_post_substep(b: Built, dt: float) -> None:
    """Integrate the interface force over the hold window: on the gripper (law) and on every arm body (diagnostic:
    shows whether part of the payload's weight reaches the arm through links other than hand and fingers)."""
    k0, k1 = b.extra["hold_k"]
    for key, bodies, out in (("force_src", "gripper_all", "impulse"), ("force_src_arm", "arm_all", "impulse_arm")):
        src = b.extra.get(key)
        if src is None:  # resolved after the first coupled step (warm-up, before any graph capture)
            found = _c01_interface_force_source(b, b.extra[bodies])
            if found is None:
                b.extra[key] = False
                continue
            arr, idx = found
            world = b.model.body_world.numpy()[b.extra[bodies]]
            b.extra[key] = src = (arr, _ids(idx, b.model.device), _ids(world, b.model.device))
        if src is False:
            continue
        arr, idx, world = src
        wp.launch(_accumulate_window_force_kernel, dim=idx.shape[0], device=b.model.device,
                  inputs=[idx, world, arr, b.extra["counter"], k0, k1, dt, b.extra[out]])


