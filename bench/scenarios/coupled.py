def _c05_fourbar(nworld: int, device: str, config: Config) -> Built:
    """Closed four-bar: Kamino+MuJoCo via SolverCoupledADMM (cross joints become ADMM attachments) or one Kamino.

    Derived from newton/examples/multiphysics/example_kamino_mujoco_admm_solver.py; the monolithic config runs the
    same model through a single SolverKamino (newton/examples/kamino/example_kamino_basic_fourbar.py settings).
    params: mode (admm | kamino), mass_scale (Kamino links x scale: the 1000:1 condition).
    """
    p = config.params
    tpl, ids = _fourbar_template(float(p.get("mass_scale", 1.0)))
    nb, nj = tpl.body_count, tpl.joint_count
    main = newton.ModelBuilder(gravity=(0.0, 0.0, -9.81))
    SolverKamino.register_custom_attributes(main)
    main.replicate(tpl, copy_count=nworld)
    main.add_ground_plane()
    main.color()
    model = main.finalize(device=device, skip_validation_joints=p["mode"] == "kamino")
    model.rigid_contact_max = 96 * nworld
    if p["mode"] == "kamino":
        cfg = _kamino_config(p.get("kamino_iterations", 200))
        solver = SolverKamino(model=model, config=cfg)
    else:
        kcfg = _kamino_config(p.get("kamino_iterations", 40))
        solver = SolverCoupledADMM(
            model=model,
            entries=[SolverCoupled.Entry(name="kamino", solver=lambda v: SolverKamino(model=v, config=kcfg),
                                         bodies=_expand(ids["kamino_bodies"], nb, nworld),
                                         joints=_expand(ids["kamino_joints"], nj, nworld),
                                         configure_view=_configure_kamino_rigid_view),
                     SolverCoupled.Entry(name="mjc", solver=lambda v: SolverMuJoCo(
                         model=v, use_mujoco_contacts=False, njmax=64 * nworld, nconmax=64 * nworld),
                         bodies=_expand(ids["mujoco_bodies"], nb, nworld),
                         joints=_expand(ids["mujoco_joints"], nj, nworld))],
            coupling=SolverCoupledADMM.Config(
                iterations=p.get("admm_iterations", 2), rho=p.get("rho", 50.0), gamma=p.get("gamma", 0.1),
                baumgarte=p.get("baumgarte", 0.02), joint_stiffness=p.get("joint_stiffness", 2.0e4),
                joint_angular_stiffness=p.get("joint_stiffness", 2.0e4), joint_damping=p.get("joint_damping", 1.0),
                joint_angular_damping=p.get("joint_damping", 1.0)))
    s0, s1, control = model.state(), model.state(), model.control()
    newton.eval_fk(model, model.joint_q, model.joint_qd, s0)
    newton.eval_fk(model, model.joint_q, model.joint_qd, s1)
    track = np.asarray(ids["kamino_bodies"] + ids["mujoco_bodies"][1:])
    # The example allocates (but never fills) a contact buffer: SolverMuJoCo needs one with use_mujoco_contacts=False.
    contacts = newton.CollisionPipeline(model).contacts()
    return Built(model, solver, s0, s1, control, contacts, None, nworld=nworld,
                 extra={"traj_bodies": track, "gap_joints": np.asarray(_expand(ids["loop_joints"], nj, nworld))})


def _c05_attach(nworld: int, device: str, config: Config) -> Built:
    """Rigid ball attached to a pinned VBD cloth + a cross-solver pendulum ball joint, via SolverCoupledADMM.

    Derived from newton/examples/multiphysics/example_mujoco_vbd_admm_solver.py (graph-safe, collide disabled as
    in the example). params: rigid (mujoco | kamino), ball_mass, attach_k (attachment stiffness [N/m]), cloth_ke.
    The attachment is compliant by construction (builder.add_attachment_particle_body, stiffness in N/m), so its
    law is Hooke's: at rest it carries the ball's weight, gap = m g / k. The rigid cross-solver ball joint keeps the
    1 mm separation law.
    """
    p = config.params
    tpl = newton.ModelBuilder()
    dim, cloth_z, r = 11, 2.0, 0.08
    p0 = tpl.particle_count
    ke = float(p.get("cloth_ke", 1.0e3))
    tpl.add_cloth_grid(pos=wp.vec3(-0.5, -0.5, cloth_z), rot=wp.quat_identity(), vel=wp.vec3(0.0), fix_left=True,
                       fix_right=True, dim_x=dim, dim_y=dim, cell_x=0.1, cell_y=0.1, mass=0.05, tri_ke=ke, tri_ka=ke,
                       tri_kd=1.0e-2 * ke, edge_ke=0.01, edge_kd=1.0e-4, particle_radius=0.01)
    center = p0 + (dim // 2) * (dim + 1) + dim // 2
    ball = tpl.add_body(xform=wp.transform(p=wp.vec3(0.0, 0.0, cloth_z - r), q=wp.quat_identity()),
                        mass=float(p.get("ball_mass", 0.5)), inertia=wp.mat33(np.eye(3) * 5.0e-3))
    ball_joint = tpl.joint_count - 1
    tpl.add_shape_sphere(ball, radius=r)
    attach_k = float(p.get("attach_k", 1.0e3))
    tpl.add_attachment_particle_body(center, ball, body_point=wp.vec3(0.0, 0.0, r), stiffness=attach_k)
    link_hx, payload_hx = 0.28, 0.12
    anchor = wp.vec3(1.4, 0.0, 2.2)
    pend = tpl.add_link(xform=wp.transform(p=anchor + wp.vec3(link_hx, 0.0, 0.0), q=wp.quat_identity()), mass=0.6,
                        inertia=wp.mat33(np.eye(3) * 1.0e-2))
    tpl.add_shape_box(pend, hx=link_hx, hy=0.045, hz=0.045)
    pend_joint = tpl.add_joint_revolute(parent=-1, child=pend, axis=wp.vec3(0.0, 1.0, 0.0), target_kd=0.5,
                                        parent_xform=wp.transform(p=anchor, q=wp.quat_identity()),
                                        child_xform=wp.transform(p=wp.vec3(-link_hx, 0.0, 0.0), q=wp.quat_identity()))
    tpl.add_articulation([pend_joint], label="pendulum")
    payload = tpl.add_body(xform=wp.transform(p=anchor + wp.vec3(2 * link_hx + payload_hx, 0.0, 0.0),
                                              q=wp.quat_identity()), mass=0.35, inertia=wp.mat33(np.eye(3) * 6.0e-3))
    payload_free = tpl.joint_count - 1
    tpl.add_shape_box(payload, hx=payload_hx, hy=0.09, hz=0.09)
    cross = tpl.add_joint_ball(parent=pend, child=payload, friction=1.0,
                               parent_xform=wp.transform(p=wp.vec3(link_hx, 0.0, 0.0), q=wp.quat_identity()),
                               child_xform=wp.transform(p=wp.vec3(-payload_hx, 0.0, 0.0), q=wp.quat_identity()),
                               collision_filter_parent=True)
    nb, nj, npart = tpl.body_count, tpl.joint_count, tpl.particle_count
    rigid_kind = p.get("rigid", "mujoco")
    if rigid_kind == "kamino":
        SolverKamino.register_custom_attributes(tpl)
    main = _replicate(tpl, nworld)
    main.add_ground_plane()
    main.color()
    model = main.finalize(device=device)
    model.soft_contact_ke = 0.0  # the attachment binds ball and cloth; soft contact would fight it (example :226)
    model.soft_contact_kd = 0.0
    rname, rfactory = _rigid_entry(rigid_kind, {"use_mujoco_contacts": False, "njmax": 32 * nworld})
    solver = SolverCoupledADMM(
        model=model,
        entries=[SolverCoupled.Entry(name=rname, solver=rfactory, bodies=_expand([ball, pend], nb, nworld),
                                     joints=_expand([ball_joint, pend_joint], nj, nworld)),
                 SolverCoupled.Entry(name="vbd", solver=lambda v: SolverVBD(model=v, iterations=8),
                                     bodies=_expand([payload], nb, nworld), joints=_expand([payload_free], nj, nworld),
                                     particles=list(range(model.particle_count)))],
        coupling=SolverCoupledADMM.Config(iterations=p.get("admm_iterations", 2), rho=p.get("rho", 50.0),
                                          gamma=p.get("gamma", 0.1), baumgarte=p.get("baumgarte", 0.01),
                                          joint_proximal_bodies=True, joint_proximal_destination_entries=(rname,)))
    s0, s1, control = model.state(), model.state(), model.control()
    newton.eval_fk(model, model.joint_q, model.joint_qd, s0)
    attach = {"ball": np.asarray(_expand([ball], nb, nworld)), "particle": np.asarray(_expand([center], npart, nworld)),
              "point": np.array([0.0, 0.0, r]),
              "expected_mm": float(p.get("ball_mass", 0.5)) * float(np.linalg.norm(_gravity(model))) / attach_k * 1e3}
    # Collision stays off as in the example (:262-265); the empty buffer satisfies SolverMuJoCo.
    contacts = newton.CollisionPipeline(model).contacts()
    return Built(model, solver, s0, s1, control, contacts, None, nworld=nworld,
                 extra={"eval_ik": True, "traj_bodies": np.asarray([ball, pend, payload]), "attach": attach,
                        "energy_law": "creation",
                        "gap_joints": np.asarray(_expand([cross, pend_joint], nj, nworld))})


