@wp.kernel
def _sand_body_forces_kernel(
    dt: float,
    collider_ids: wp.array(dtype=int),
    collider_impulses: wp.array(dtype=wp.vec3),
    collider_impulse_pos: wp.array(dtype=wp.vec3),
    body_ids: wp.array(dtype=int),
    body_q: wp.array(dtype=wp.transform),
    body_com: wp.array(dtype=wp.vec3),
    body_f: wp.array(dtype=wp.spatial_vector),
):
    """Sand impulses -> body wrenches at the COM (copy of example_mpm_twoway_coupling.py:25-53)."""
    i = wp.tid()
    cid = collider_ids[i]
    if cid >= 0 and cid < body_ids.shape[0]:
        body = body_ids[cid]
        if body == -1:
            return
        f = collider_impulses[i] / dt
        r = collider_impulse_pos[i] - wp.transform_point(body_q[body], body_com[body])
        wp.atomic_add(body_f, body, wp.spatial_vector(f, wp.cross(r, f)))


@wp.kernel
def _subtract_body_force_kernel(
    dt: float,
    body_q: wp.array(dtype=wp.transform),
    body_qd: wp.array(dtype=wp.spatial_vector),
    body_f: wp.array(dtype=wp.spatial_vector),
    body_inv_inertia: wp.array(dtype=wp.mat33),
    body_inv_mass: wp.array(dtype=float),
    body_q_res: wp.array(dtype=wp.transform),
    body_qd_res: wp.array(dtype=wp.spatial_vector),
):
    """Remove the sand force applied last frame from the collider velocity (example_mpm_twoway_coupling.py:56-83)."""
    b = wp.tid()
    f = body_f[b]
    dv = dt * body_inv_mass[b] * wp.spatial_top(f)
    r = wp.transform_get_rotation(body_q[b])
    dw = dt * wp.quat_rotate(r, body_inv_inertia[b] * wp.quat_rotate_inv(r, wp.spatial_bottom(f)))
    body_q_res[b] = body_q[b]
    body_qd_res[b] = body_qd[b] - wp.spatial_vector(dv, dw)


def _mpm_config(voxel: float, nworld: int, *, iterations: int = 50, padding: int = 50,
                cells_per_world: int = 1 << 15, velocity_mode: str | None = None) -> SolverImplicitMPM.Config:
    """Fixed-grid implicit MPM as in the coupled examples; separate_worlds keeps replicated beds independent."""
    c = SolverImplicitMPM.Config()
    c.voxel_size = voxel
    c.grid_type = "fixed"
    c.grid_padding = padding
    c.max_active_cell_count = cells_per_world * nworld
    c.strain_basis = "P0"
    c.max_iterations = iterations
    c.critical_fraction = 0.0
    c.separate_worlds = True
    if velocity_mode is not None:
        c.collider_velocity_mode = velocity_mode
    return c


def _add_sand_block(builder: newton.ModelBuilder, lo, hi, voxel: float, ppc: float, density: float,
                    attrs: dict, jitter_frac: float = 2.0, radius_frac: float = 0.5) -> list[int]:
    """Jittered particle block (example_mujoco_mpm_coupled_solver.py:265-292)."""
    lo, hi = np.asarray(lo, dtype=np.float64), np.asarray(hi, dtype=np.float64)
    res = np.maximum(1, np.ceil(ppc * (hi - lo) / voxel).astype(int))
    cell = (hi - lo) / res
    radius = float(np.max(cell) * radius_frac)
    start = builder.particle_count
    builder.add_particle_grid(pos=wp.vec3(*lo), rot=wp.quat_identity(), vel=wp.vec3(0.0), dim_x=int(res[0]) + 1,
                              dim_y=int(res[1]) + 1, dim_z=int(res[2]) + 1, cell_x=float(cell[0]),
                              cell_y=float(cell[1]), cell_z=float(cell[2]), mass=float(np.prod(cell) * density),
                              jitter=jitter_frac * radius, radius_mean=radius, custom_attributes=attrs)
    return list(range(start, builder.particle_count))


class _StaticImpulseLedger:
    """Accumulates the impulse static MPM colliders (floor) apply to the material, after every MPM step, on device.

    The impulses come from SolverImplicitMPM.collect_collider_impulses (public), which returns the impulse the
    material applies to each collider (-cell_volume * impulse_field, newton@ac7f7830
    solver_implicit_mpm.py:2399-2417); value() returns its negative, the impulse on the material. Which colliders
    count as static is given by collider ids (default: every collider whose body index is -1).
    """

    def __init__(self, mpm_solver, states: Callable[[], list], device, static_ids: Sequence[int] | None = None):
        self.mpm = mpm_solver
        self.states = states
        body_index = mpm_solver.collider_body_index.numpy()
        flags = (body_index == -1).astype(np.int32) if static_ids is None else np.zeros(len(body_index), np.int32)
        if static_ids is not None:
            flags[list(static_ids)] = 1
        self.is_static = wp.array(flags, dtype=int, device=device)
        self.total = wp.zeros(3, dtype=wp.float64, device=device)
        self._state = None

    def _impulse_state(self):
        if self._state is None:
            for st in self.states():
                if st is not None and hasattr(st, "impulse_field"):
                    self._state = st
                    break
        return self._state

    def accumulate(self) -> None:
        st = self._impulse_state()
        if st is None:
            return
        imp, _pos, cid = self.mpm.collect_collider_impulses(st)
        if cid.shape[0] == 0:
            return
        wp.launch(_accumulate_static_impulse_kernel, dim=cid.shape[0], device=self.total.device,
                  inputs=[imp, cid, self.is_static, self.total])

    def value(self) -> np.ndarray:
        """Cumulative impulse the static colliders applied to the material [N s] (sign flipped, see class doc)."""
        return -self.total.numpy().copy()


def _momentum(model, body_q, body_qd, particle_qd, bodies: np.ndarray | None,
              particles: np.ndarray | None) -> np.ndarray:
    """Total linear momentum [kg m/s] of the given bodies (COM velocity) and particles."""
    p = np.zeros(3)
    if bodies is not None and len(bodies):
        p += (model.body_mass.numpy()[bodies, None] * body_qd[bodies, :3]).sum(axis=0)
    if particles is not None and len(particles):
        p += (model.particle_mass.numpy()[particles, None] * particle_qd[particles]).sum(axis=0)
    return p


def _ledger_residual(p0: np.ndarray, p1: np.ndarray, j_static: np.ndarray, mass: float, g: np.ndarray, T: float,
                     m_obj: float) -> dict:
    """Momentum ledger: residual = (p1 - p0) - (M g T + J_static); relative to |M g| T and to the object's m g T."""
    res = (p1 - p0) - (mass * g * T + j_static)
    gi = float(np.linalg.norm(g)) * T
    return {"momentum_residual_pct": float(np.linalg.norm(res) / max(mass * gi, 1e-12) * 100.0),
            "momentum_residual_obj_pct": float(np.linalg.norm(res) / max(m_obj * gi, 1e-12) * 100.0),
            "momentum_residual_ns": res.tolist(), "ledger_T_s": T}


