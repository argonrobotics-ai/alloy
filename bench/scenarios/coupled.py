@wp.kernel
def _integrate_spatial_force_kernel(ids: wp.array(dtype=int), force: wp.array(dtype=wp.spatial_vector), h: float,
                                    out: wp.array(dtype=wp.vec3d)):
    i = wp.tid()
    f = wp.spatial_top(force[ids[i]])
    out[i] = out[i] + wp.vec3d(wp.float64(f[0] * h), wp.float64(f[1] * h), wp.float64(f[2] * h))


@wp.kernel
def _integrate_vec3_force_kernel(ids: wp.array(dtype=int), force: wp.array(dtype=wp.vec3), h: float,
                                 out: wp.array(dtype=wp.vec3d)):
    i = wp.tid()
    f = force[ids[i]]
    out[i] = out[i] + wp.vec3d(wp.float64(f[0] * h), wp.float64(f[1] * h), wp.float64(f[2] * h))


class _ImpulseIntegrator:
    """Cumulative impulse of an interface force on a fixed id set, integrated on device after every coupled step.

    The coupler's harvested force is a per-step value; one host snapshot per sample is noise. Sampling the running
    impulse J(t) and differencing, F_mean = (J(t1) - J(t0)) / (t1 - t0), gives the exact time average over any window
    chosen afterwards. `source()` returns the force array (resolved lazily, after the solver has stepped once, so it
    happens during warm-up and never inside a graph capture) or None.
    """

    def __init__(self, source: Callable[[], wp.array | None], ids: np.ndarray, device):
        self.source = source
        self.ids = _ids(ids, device)
        self.total = wp.zeros(len(ids), dtype=wp.vec3d, device=device)
        self._arr: wp.array | None | bool = None

    def accumulate(self, h: float) -> None:
        if self._arr is None:
            arr = self.source()
            self._arr = arr if arr is not None else False
        if self._arr is False:
            return
        kernel = _integrate_spatial_force_kernel if self._arr.dtype == wp.spatial_vector else \
            _integrate_vec3_force_kernel
        wp.launch(kernel, dim=self.ids.shape[0], inputs=[self.ids, self._arr, h, self.total], device=self.total.device)

    @property
    def available(self) -> bool:
        return self._arr is not None and self._arr is not False

    def value(self) -> np.ndarray:
        return self.total.numpy().astype(np.float64).copy()


def _proxy_force_array(solver, kind: str) -> wp.array | None:
    """The (single) proxy feedback array of a SolverCoupledProxy, global ids (private attribute, see module doc)."""
    maps = getattr(solver, "_proxy_mappings" if kind == "body" else "_proxy_particle_mappings", None)
    if not maps:
        return None
    if len(maps) > 1:
        raise RuntimeError("expected one proxy mapping; sum several in _ImpulseIntegrator before using this")
    return maps[0].coupling_forces


def _mean_force(samples: list[tuple[float, np.ndarray]], t0: float, t1: float) -> np.ndarray | None:
    """Time-averaged force from cumulative impulse samples over [t0, t1] (first and last sample inside it)."""
    win = _window(samples, t0, t1)
    if len(win) < 2 or win[-1][0] - win[0][0] <= 0:
        return None
    return (win[-1][1] - win[0][1]) / (win[-1][0] - win[0][0])


