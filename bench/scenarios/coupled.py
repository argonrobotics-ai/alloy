def _c03_strap(hx: float, hz: float, width: float, nu: int = 120, nv: int = 6) -> tuple[np.ndarray, np.ndarray]:
    """Closed cloth loop around a hx x hz box in the x-z plane (example_softbody_gift.py:cloth_loop_around_box)."""
    perim = 4.0 * (hx + hz)
    verts = []
    for i in range(nu):
        a = i / nu * perim
        if a < 2 * hx:
            x, z = -hx + a, -hz
        elif a < 2 * hx + 2 * hz:
            x, z = hx, -hz + (a - 2 * hx)
        elif a < 4 * hx + 2 * hz:
            x, z = hx - (a - (2 * hx + 2 * hz)), hz
        else:
            x, z = -hx, hz - (a - (4 * hx + 2 * hz))
        verts += [[x, (j / (nv - 1) - 0.5) * width, z] for j in range(nv)]
    idx = lambda i, j: (i % nu) * nv + j  # noqa: E731
    faces = [f for i in range(nu) for j in range(nv - 1)
             for f in ((idx(i, j), idx(i + 1, j), idx(i, j + 1)), (idx(i + 1, j), idx(i + 1, j + 1), idx(i, j + 1)))]
    return np.asarray(verts, np.float32), np.asarray(faces, np.int32)


def _c03_drop_template(tpl: newton.ModelBuilder, p: dict) -> tuple[list[int], list[int]]:
    """Cloth pinned on two edges + a tet block above it (example_softbody_dropping_to_cloth.py, smaller)."""
    c = C03_CLOTH
    c0 = tpl.particle_count
    cloth_kw = dict(pos=wp.vec3(c["x0"], c["y0"], c["z"]), rot=wp.quat_identity(), vel=wp.vec3(0.0), fix_left=True,
                    fix_right=True, dim_x=c["dim"], dim_y=c["dim"], cell_x=c["cell"], cell_y=c["cell"], mass=0.0005,
                    tri_ke=1e5, tri_ka=1e5, tri_kd=1e0, edge_ke=0.01, edge_kd=1e-4,
                    particle_radius=p.get("cloth_radius", 0.05))
    if p.get("cloth_solver") == "xpbd":  # XPBD has no triangle membrane term (solver_xpbd.py:734-800): springs.
        # Newton's XPBD sums spring corrections Jacobi-style without averaging (xpbd/kernels.py:321-386, 847-876),
        # so it diverges once ke * h^2 / m exceeds ~0.15 (measured: ke 100 N/m fails at h = 1/600 s, 1000 N/m passes
        # at h = 1/6000 s, cloth particle 0.5 g; bench/notes/coupled.md). The XPBD cloth therefore runs
        # cloth_substeps substeps per coupled step with spring_ke at that limit: a softer cloth than VBD's.
        cloth_kw.update(add_springs=True, spring_ke=p.get("spring_ke", 1.0e3), spring_kd=0.0)
    tpl.add_cloth_grid(**cloth_kw)
    cloth = list(range(c0, tpl.particle_count))
    s0 = tpl.particle_count
    tpl.add_soft_grid(pos=wp.vec3(-0.2, -0.2, 1.3), rot=wp.quat_identity(), vel=wp.vec3(0.0), dim_x=4, dim_y=4,
                      dim_z=2, cell_x=0.1, cell_y=0.1, cell_z=0.1, density=1.0e3, k_mu=1.0e5, k_lambda=1.0e5,
                      k_damp=1.0e2, particle_radius=0.03)
    return cloth, list(range(s0, tpl.particle_count))


def _c03_gift_template(tpl: newton.ModelBuilder) -> tuple[list[int], list[int], list[list[int]]]:
    """Four stacked soft blocks tied by two crossed cloth straps (example_softbody_gift.py, dropped from 0.5 m, with
    C03_GIFT_CLEAR initial clearances)."""
    clear = C03_GIFT_CLEAR
    base, spacing = C03_GIFT_BASE_Z, 1.0 + clear
    half_x, half_z = 1.0, 0.5 * (3.0 * spacing + 1.0)  # stack half extents (blocks are 2 x 2 x 1 m)
    s0 = tpl.particle_count
    for i in range(4):
        tpl.add_soft_mesh(pos=(0.0, 0.0, base + i * spacing), rot=wp.quat_identity(), scale=1.0, vel=(0.0, 0.0, 0.0),
                          vertices=C03_GIFT_PARTICLES, indices=C03_GIFT_TETS, density=100, k_mu=1.0e5, k_lambda=1.0e5,
                          k_damp=1e0)
    soft = list(range(s0, tpl.particle_count))
    straps = []
    loops = ((half_x + clear, half_z + clear, 0.0), (half_x + 2 * clear, half_z + 2 * clear, -0.5 * np.pi))
    for hx, hz, ang in loops:  # example: (1.01, 2.02) and (1.015, 2.025)
        verts, faces = _c03_strap(hx, hz, 0.6)
        c0 = tpl.particle_count
        tpl.add_cloth_mesh(pos=(1.0, 1.0, base + half_z),
                           rot=wp.quat_from_axis_angle(wp.vec3(0.0, 0.0, 1.0), float(ang)), scale=1.0,
                           vel=(0.0, 0.0, 0.0), vertices=verts, indices=faces.flatten().tolist(), density=0.02,
                           tri_ke=1e5, tri_ka=1e5, tri_kd=1e0, edge_ke=0.01, edge_kd=1e-4)
        straps.append(list(range(c0, tpl.particle_count)))
    return [i for st in straps for i in st], soft, straps


def _restrict_surface(view: ModelView, model, particles: np.ndarray) -> None:
    """Keep only the triangles and bending edges whose vertices all belong to `particles`, as view-local arrays.

    Used for the gift's soft entry, so its VBD self-contact sees the blocks' own surface (block-block contact) and
    not the straps. Every TRIANGLE / EDGE frequency array of the model is subset consistently.
    """
    own = np.zeros(model.particle_count, dtype=bool)
    own[np.asarray(particles)] = True
    tri = model.tri_indices.numpy()
    edges = model.edge_indices.numpy()
    edge_owned = ((edges < 0) | own[np.maximum(edges, 0)]).all(axis=1) & (edges[:, 2:] >= 0).all(axis=1)
    keep = {"TRIANGLE": np.nonzero(own[tri].all(axis=1))[0], "EDGE": np.nonzero(edge_owned)[0]}
    for name in dir(model):
        spec = model._attribute_spec(name)
        arr = getattr(model, name, None) if spec is not None else None
        freq = getattr(getattr(spec, "frequency", None), "name", None)
        if freq in keep and isinstance(arr, wp.array):
            setattr(view, name, wp.array(arr.numpy()[keep[freq]], dtype=arr.dtype, device=arr.device))
    view.tri_count = int(keep["TRIANGLE"].size)
    view.edge_count = int(keep["EDGE"].size)


def _c03_scene(nworld: int, device: str, config: Config) -> Built:
    """Soft on cloth: monolithic VBD or proxy (VBD soft -> VBD/XPBD cloth), for two scenes.

    scene "drop": tet block dropped onto a cloth pinned on two edges. Derived from
    newton/examples/multiphysics/example_softbody_dropping_to_cloth.py (both paths, its view configuration) and
    example_xpbd_vbd_coupled_solver.py (XPBD destination with a stripped view). Cloth 20 x 20 cells (example 40 x 40),
    block 4 x 4 x 2 cells (example 6 x 6 x 3) so the Mac smoke test runs.
    scene "gift": example_softbody_gift.py (monolithic VBD only in Newton); the proxy split puts the four blocks in
    one VBD and the straps in another. params: scene, mode (mono | proxy), cloth_solver (vbd | xpbd).
    """
    p = config.params
    gift = p.get("scene", "drop") == "gift"
    xpbd_cloth = p.get("cloth_solver") == "xpbd"
    tpl = newton.ModelBuilder()
    straps = None
    if gift:
        cloth, soft, straps = _c03_gift_template(tpl)
    else:
        cloth, soft = _c03_drop_template(tpl, p)
    npw = tpl.particle_count
    main = _replicate(tpl, nworld)
    main.add_ground_plane()
    main.color()
    model = main.finalize(device=device)
    if gift:  # example_softbody_gift.py:215-228
        model.soft_contact_ke, model.soft_contact_kd, model.soft_contact_mu = 5.0e4, 5.0e-1, 1.0
        vbd_kw = dict(iterations=p.get("vbd_iterations", 15), particle_enable_self_contact=True,
                      particle_self_contact_margin=0.04, particle_self_contact_gap=0.02,
                      particle_topological_contact_filter_threshold=1, particle_enable_tile_solve=False)
    else:  # example_softbody_dropping_to_cloth.py:87-100
        model.soft_contact_ke, model.soft_contact_kd, model.soft_contact_mu = 1.0e5, 1e0, 1.0
        vbd_kw = dict(iterations=p.get("vbd_iterations", 10), particle_enable_self_contact=True,
                      particle_self_contact_margin=0.01, particle_self_contact_gap=0.01,
                      particle_enable_tile_solve=True)
    cloth_all, soft_all = _expand(cloth, npw, nworld), _expand(soft, npw, nworld)
    if p["mode"] == "mono":
        solver = SolverVBD(model=model, **vbd_kw)
    else:
        def soft_view(view: ModelView) -> None:
            # drop: the example's soft view (no surface, no self-contact). gift: four blocks must still collide with
            # each other, so the soft entry keeps the blocks' own surface and its self-contact (the example's view
            # removed block-block contact and the stack interpenetrated: 2.43 m vs 4.06 m tall at 0.3 s).
            if gift:
                _restrict_surface(view, model, np.asarray(soft_all))
            else:
                view.tri_count = 0
                view.edge_count = 0
            view.spring_count = 0

        def cloth_view(view: ModelView) -> None:
            view.tet_count = 0

        soft_kw = vbd_kw if gift else {**vbd_kw, "particle_enable_self_contact": False}
        if xpbd_cloth:
            cloth_factory = lambda v: SolverXPBD(model=v, iterations=p.get("xpbd_iterations", 20),  # noqa: E731
                                                 soft_contact_relaxation=p.get("xpbd_contact_relaxation", 0.85))
        else:
            cloth_factory = lambda v: SolverVBD(model=v, **vbd_kw)  # noqa: E731
        solver = SolverCoupledProxy(
            model=model,
            entries=[SolverCoupledProxy.Entry(name="soft", solver=lambda v: SolverVBD(model=v, **soft_kw),
                                              particles=soft_all, configure_view=soft_view),
                     SolverCoupledProxy.Entry(name="cloth", solver=cloth_factory, particles=cloth_all,
                                              configure_view=cloth_view, substeps=p.get("cloth_substeps", 1))],
            coupling=SolverCoupledProxy.Config(
                proxies=[SolverCoupledProxy.Proxy(source="soft", destination="cloth", particles=soft_all,
                                                  mass_scale=p.get("mass_scale", 1.0),
                                                  mode=p.get("coupling_mode", "lagged"))],
                iterations=p.get("proxy_iterations", 1)))
    s0, s1, control = model.state(), model.state(), model.control()
    pipeline = newton.CollisionPipeline(model)
    contacts = pipeline.contacts()
    iface = _ImpulseIntegrator(lambda: _proxy_force_array(solver, "particle"), np.asarray(soft_all), device)
    return Built(model, solver, s0, s1, control, contacts, pipeline, nworld=nworld,
                 extra={"cloth": np.asarray(cloth_all), "soft": np.asarray(soft_all), "npw": npw, "gift": gift,
                        "iface": iface, "post_substep": lambda b, dt: b.extra["iface"].accumulate(dt),
                        "straps": [np.asarray(_expand(st, npw, nworld)).reshape(nworld, -1) for st in straps]
                        if straps else None,
                        "ncloth": len(cloth), "nsoft": len(soft), "energy_law": "creation"})


def _c03_pass_through(cloth_q: np.ndarray, soft_q: np.ndarray, tol: float) -> int:
    """Soft particles below the cloth: z below the nearest-in-xy cloth particle by more than tol, inside the cloth
    footprint. A cheap stand-in for a mesh intersection test (approximate, see notes)."""
    lo, hi = cloth_q[:, :2].min(axis=0) + 0.05, cloth_q[:, :2].max(axis=0) - 0.05
    inside = np.all((soft_q[:, :2] > lo) & (soft_q[:, :2] < hi), axis=1)
    if not np.any(inside):
        return 0
    s = soft_q[inside]
    d2 = ((s[:, None, :2] - cloth_q[None, :, :2]) ** 2).sum(axis=2)
    nearest_z = cloth_q[np.argmin(d2, axis=1), 2]
    return int(np.sum(s[:, 2] < nearest_z - tol))


class SoftOnCloth(_CoupledScenario):
    """C03: pinned reactions = total weight within 2 %, zero intersections, coupled-vs-monolithic sag [mm].

    Gift scene: ground support = total weight within 2 % at rest, straps stay on the stack, nothing below the floor,
    coupled-vs-monolithic stack position [mm].
    """

    id = "C03_soft_on_cloth"
    title = ("Neo-Hookean tet block dropped onto a pinned cloth, and the soft gift with cloth straps: monolithic VBD "
             "vs proxy VBD soft + VBD/XPBD cloth")
    horizon_s = 5.0  # the 32 kg block still oscillates on the cloth at 3 s (mono_vbd support error 7.8 % at 3 s)
    accuracy_unit = "%"
    accuracy_ref = "|pinned reaction - total weight| / weight; reaction from the momentum balance over the last 1 s"
    ladder = (1, 16, 256, 1024)
    sample_every = 3
    rest_window_s = 1.0
    _F = 1.0 / 60.0
    configs = (
        Config("mono_vbd", "vbd", dt=_F, substeps=10, params={"mode": "mono"}, max_nworld=256),
        Config("proxy_vbd_vbd", "proxy:vbd+vbd", dt=_F, substeps=10, params={"mode": "proxy", "ref": "mono_vbd"},
               max_nworld=256),
        Config("proxy_vbd_xpbd", "proxy:vbd+xpbd", dt=_F, substeps=10,
               params={"mode": "proxy", "cloth_solver": "xpbd", "cloth_radius": 0.024, "spring_ke": 1.0e3,
                       "cloth_substeps": 10, "ref": "mono_vbd"},
               max_nworld=256),
        Config("gift_mono_vbd", "vbd", dt=_F, substeps=10, params={"scene": "gift", "mode": "mono"}, max_nworld=256),
        # max_nworld 1: with VBD self-contact on in the soft entry (needed for block-block contact), nworld >= 2
        # segfaults inside SolverVBD on CPU (bench/notes/coupled.md, C03 known problems).
        Config("gift_proxy_vbd_vbd", "proxy:vbd+vbd", dt=_F, substeps=10,
               params={"scene": "gift", "mode": "proxy", "ref": "gift_mono_vbd"}, max_nworld=1),
    )

    def _scene(self, nworld: int, device: str, config: Config) -> Built:
        return _c03_scene(nworld, device, config)

    def on_start(self, b: Built, rec: dict) -> None:
        model = b.model
        mass = model.particle_mass.numpy().astype(np.float64)
        b.extra.update(pz=[], fz=[], pass_max=0, mass=mass, weight=float(mass.sum() * np.linalg.norm(_gravity(model))),
                       soft_weight=float(mass[b.extra["soft"]].sum() * np.linalg.norm(_gravity(model))),
                       ground_touch=0)

    def measure(self, b: Built, t: float, rec: dict) -> None:
        super().measure(b, t, rec)
        q = b.state_0.particle_q.numpy().astype(np.float64)
        qd = b.state_0.particle_qd.numpy().astype(np.float64)
        b.extra["pz"].append((t, float(np.sum(b.extra["mass"] * qd[:, 2]))))
        if b.extra["iface"].available:
            b.extra["fz"].append((t, b.extra["iface"].value()[:, 2].reshape(b.nworld, -1).sum(axis=1)))
        b.extra["q_last"] = q
        if b.extra["gift"]:  # the gift rests on the ground: count particles below it instead
            b.extra["below_floor"] = max(b.extra.get("below_floor", 0), int(np.sum(q[:, 2] < -0.01)))
            return
        nw = b.nworld
        for w in range(nw):
            cl = q[b.extra["cloth"][w * b.extra["ncloth"]:(w + 1) * b.extra["ncloth"]]]
            so = q[b.extra["soft"][w * b.extra["nsoft"]:(w + 1) * b.extra["nsoft"]]]
            b.extra["pass_max"] = max(b.extra["pass_max"], _c03_pass_through(cl, so, tol=0.02))
        radius = b.model.particle_radius.numpy()
        moving = b.extra["mass"] > 0
        b.extra["ground_touch"] = int(np.sum(moving & (q[:, 2] < radius + 0.002)))

    def finish(self, b: Built, rec: dict) -> None:
        super().finish(b, rec)
        t_end = b.extra.get("t_last", 0.0)
        t0 = t_end - self.rest_window_s
        win = _window(b.extra["pz"], t0, t_end)
        dpdt = _slope([t for t, _ in win], [v for _, v in win])
        W = b.extra["weight"]
        reaction = dpdt + W  # dP_z/dt = R_z - W
        support_err = abs(reaction - W) / W * 100.0
        if b.extra["gift"]:
            self._finish_gift(b, rec, support_err, reaction, W)
            return
        q = b.extra["q_last"]
        cz = q[b.extra["cloth"], 2].reshape(b.nworld, -1)
        sag_mm = float(np.max(C03_CLOTH["z"] - cz.min(axis=1)) * 1e3)
        fz = _mean_force(b.extra["fz"], t0, t_end)  # per world: interface force on the soft block [N]
        w_soft = b.extra["soft_weight"] / b.nworld
        iface = float(np.max(np.abs(fz - w_soft)) / w_soft * 100.0) if fz is not None else None
        p = rec["params"]
        ref = _load_ref(self.id, p["ref"], rec) if p.get("ref") else None
        sag_diff = abs(sag_mm - ref["sag_mm"]) if ref and ref.get("sag_mm") is not None else None
        m = rec["metrics"]
        m.update(support_err_pct=support_err, pinned_reaction_n=reaction, total_weight_n=W, sag_mm=sag_mm,
                 sag_diff_mm=sag_diff, sag_ref=p.get("ref"), intersections=b.extra["pass_max"],
                 ground_contact_particles=b.extra["ground_touch"], interface_support_err_pct=iface,
                 law_pass=bool(support_err <= 2.0 and b.extra["pass_max"] == 0 and b.extra["ground_touch"] == 0
                               and m["energy_ok"]),
                 ref_payload={"sag_mm": sag_mm})
        rec["accuracy_error"] = support_err
        _store_ref(self.id, rec, {"sag_mm": sag_mm})

    def _finish_gift(self, b: Built, rec: dict, support_err: float, reaction: float, W: float) -> None:
        """Gift laws: ground support at rest, straps retained around the stack, nothing below the floor."""
        q, nw = b.extra["q_last"], b.nworld
        soft = q[b.extra["soft"]].reshape(nw, -1, 3)
        lo, hi = soft.min(axis=1), soft.max(axis=1)
        lost = 0
        for st in b.extra["straps"]:
            sq = q[st.reshape(-1)].reshape(nw, -1, 3)
            c = sq.mean(axis=1)
            inside = np.all((c[:, :2] > lo[:, :2] - 0.1) & (c[:, :2] < hi[:, :2] + 0.1), axis=1)
            span = (sq[:, :, 2].max(axis=1) - sq[:, :, 2].min(axis=1)) / np.maximum(hi[:, 2] - lo[:, 2], 1e-6)
            lost += int(np.sum(~inside | (span < 0.5)))
        com = soft.mean(axis=1)
        p = rec["params"]
        ref = _load_ref(self.id, p["ref"], rec) if p.get("ref") else None
        dev = (float(np.max(np.linalg.norm(com - np.asarray(ref["stack_com"]), axis=1)) * 1e3)
               if ref and ref.get("stack_com") is not None and np.asarray(ref["stack_com"]).shape == com.shape
               else None)
        below = b.extra.get("below_floor", 0)
        m = rec["metrics"]
        m.update(support_err_pct=support_err, ground_reaction_n=reaction, total_weight_n=W, straps_lost=lost,
                 below_floor=below, stack_height_mm=float(np.max(hi[:, 2] - lo[:, 2]) * 1e3), stack_dev_mm=dev,
                 stack_ref=p.get("ref"),
                 law_pass=bool(support_err <= 2.0 and lost == 0 and below == 0 and m["energy_ok"]),
                 ref_payload={"stack_com": com.tolist()})
        rec["accuracy_error"] = support_err
        _store_ref(self.id, rec, {"stack_com": com.tolist()})


