"""Coupled multi-solver family (bench/SCENARIOS.md §1.5): SolverCoupledProxy and SolverCoupledADMM baselines.

    python -m bench.run --family coupled --device cpu --ladder 1 --horizon 0.3 --repeat-max-nworld 0   # Mac smoke
    python -m bench.run --family coupled --scenario C05_rigid_deform_attach --device cuda:0 --ladder 1,16,256

Every scene is derived from a Newton example (newton@ac7f7830, paths under newton/examples/); the docstring of each
scene builder names it. Laws and metric definitions are in bench/notes/coupled.md. Shared measurement machinery:

- energy ledger: KE + gravitational PE of a tracked body/particle set, evaluated on device after every outer step
  (one "tick"); a tick whose energy rises by more than 1 mJ in a world is an energy-gain event (CON-30). Elastic
  energy is not included, so elastic rebound can register as a gain (documented, not hidden).
- momentum ledger (MPM scenes): P_end - P_start = M g T + J_static, with J_static the impulse that static MPM
  colliders (floor) applied, accumulated on device from SolverImplicitMPM.collect_collider_impulses after every step.
- interface force: the coupler's own harvested force. Proxy: SolverCoupledProxy._proxy_mappings[*].coupling_forces
  (private attribute, global ids, [N]). ADMM: SolverCoupledADMM._admm_buffers[entry].body_f (private). Explicit
  baseline: the hand-rolled sand wrench of newton/examples/mpm/example_mpm_twoway_coupling.py. Integrated on device
  after every coupled step (_ImpulseIntegrator) so rest-window means are exact time averages, not snapshots.
- scripted robot motion (C01): joint targets precomputed with Newton IK at build time, replayed from a device table
  indexed by the step counter (graph-safe).
- Do not edit this file while a run is in progress: Warp reads kernel source lazily from disk when the module is
  first built, and shifted line numbers make it parse the wrong function (WarpCodegenKeyError).
- references: coupled-vs-monolithic comparisons (sag, trajectory) read the reference config's result from this
  process, else from the latest matching row in bench/results/coupled/<scenario>.jsonl.
"""
