# Energy ledger
# =====================================================================================================
class _EnergyTracker:
    """Per-world KE + gravitational PE of a body/particle set.

    Two checks: (1) tick events, a rise of more than threshold between consecutive outer steps, counted only for
    step indices in [k0, k1) (CON-30); (2) creation, max_t E(t) - E(0). For a passive system that starts at its
    rest shape, E_kin + E_pot <= E(0) at all times because elastic energy and dissipation are nonnegative, so
    creation > threshold is a violation even when elastic rebound makes tick events legitimate.
    """

    def __init__(self, model, nworld: int, bodies: np.ndarray | None, particles: np.ndarray | None,
                 counter: wp.array, threshold_j: float = ENERGY_TICK_J, window: tuple[int, int] = (0, 1 << 30)):
        dev = model.device
        self.model = model
        self.counter = counter
        self.window = (int(window[0]), int(window[1]))
        self.g = wp.vec3(*[float(x) for x in _gravity(model)])
        self.bodies = _ids(bodies, dev) if bodies is not None and len(bodies) else None
        if particles is not None and len(particles):
            pmass = model.particle_mass.numpy()[np.asarray(particles)]
            particles = np.asarray(particles)[pmass > 0.0]  # pinned particles carry no energy
        self.particles = _ids(particles, dev) if particles is not None and len(particles) else None
        self.threshold = wp.float64(threshold_j)
        self.e_now = wp.zeros(nworld, dtype=wp.float64, device=dev)
        self.e_prev = wp.zeros(nworld, dtype=wp.float64, device=dev)
        self.e_max = wp.full(nworld, -1.0e30, dtype=wp.float64, device=dev)
        self.events = wp.zeros(nworld, dtype=int, device=dev)
        self.max_gain = wp.full(nworld, -1.0e30, dtype=wp.float64, device=dev)
        self.armed = wp.zeros(1, dtype=int, device=dev)
        self.e0: np.ndarray | None = None

    def prime(self, state) -> None:
        """Evaluate E(0) (host read; call once at build time, outside the timed loop)."""
        self.update(state)
        self.e0 = self.e_now.numpy().copy()

    def update(self, state) -> None:
        m, dev = self.model, self.model.device
        self.e_now.zero_()
        if self.bodies is not None:
            wp.launch(_body_energy_kernel, dim=self.bodies.shape[0], device=dev,
                      inputs=[self.bodies, state.body_q, state.body_qd, m.body_mass, m.body_inertia, m.body_com,
                              m.body_world, self.g, self.e_now])
        if self.particles is not None:
            wp.launch(_particle_energy_kernel, dim=self.particles.shape[0], device=dev,
                      inputs=[self.particles, state.particle_q, state.particle_qd, m.particle_mass, m.particle_world,
                              self.g, self.e_now])
        wp.launch(_energy_event_kernel, dim=self.e_now.shape[0], device=dev,
                  inputs=[self.e_now, self.e_prev, self.armed, self.counter, self.window[0], self.window[1],
                          self.threshold, self.events, self.max_gain, self.e_max])
        wp.launch(_arm_kernel, dim=1, inputs=[self.armed], device=dev)

    def results(self) -> dict:
        ev = self.events.numpy()
        gain = self.max_gain.numpy()
        creation = (self.e_max.numpy() - self.e0) if self.e0 is not None else None
        return {"energy_gain_events": int(ev.sum()), "energy_gain_worlds": int((ev > 0).sum()),
                "energy_max_tick_gain_mj": float(gain.max() * 1e3) if gain.size and gain.max() > -1e29 else None,
                "energy_creation_mj": float(creation.max() * 1e3) if creation is not None else None}


