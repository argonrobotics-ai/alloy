# Bed lifted 0.035 m as in example_xpbd_mpm_coupled_solver.py:240, so jittered particles never start below z = 0
# (a bed starting at z = 0 puts ~4 % of its particles below the floor and fakes the "below floor" count).
C04_BED = dict(lo=(-0.34, -0.34, 0.035), hi=(0.34, 0.34, 0.335), voxel=0.06, ppc=1.85, density=1500.0)
C04_BED_ATTRS = {"mpm:friction": 0.42, "mpm:yield_pressure": 1.0e5, "mpm:tensile_yield_ratio": 0.0}
C04_XPBD = dict(dim=(8, 8, 4), radius=0.022, mass=0.018, z0=0.45, vz=-0.25)


def _c04_xpbd_cluster(builder: newton.ModelBuilder, as_mpm: bool) -> list[int]:
    """Particle cluster of example_xpbd_mpm_coupled_solver.py:229-245 (lower start: our bed is 0.30 m deep)."""
    c = C04_XPBD
    r = c["radius"]
    start = builder.particle_count
    kw = {"custom_attributes": {"mpm:friction": 0.25}} if as_mpm else {}
    nx = c["dim"][0]
    builder.add_particle_grid(pos=wp.vec3(-0.5 * nx * 2.08 * r, -0.5 * nx * 2.08 * r, c["z0"]), rot=wp.quat_identity(),
                              vel=wp.vec3(0.0, 0.0, c["vz"]), dim_x=c["dim"][0], dim_y=c["dim"][1], dim_z=c["dim"][2],
                              cell_x=2.08 * r, cell_y=2.08 * r, cell_z=2.08 * r, mass=c["mass"], jitter=0.10 * r,
                              radius_mean=r, **kw)
    return list(range(start, builder.particle_count))


def _c04_soft_cube(builder: newton.ModelBuilder) -> list[int]:
    """VBD tet cube of example_vbd_mpm_coupled_solver.py:236-262 (3^3 cells of 8 cm; example 4^3 of 11 cm)."""
    start = builder.particle_count
    k = 2.0e4
    builder.add_soft_grid(pos=wp.vec3(-0.12, -0.12, 0.45), rot=wp.quat_identity(), vel=wp.vec3(0.0, 0.0, -0.4),
                          dim_x=3, dim_y=3, dim_z=3, cell_x=0.08, cell_y=0.08, cell_z=0.08, density=420.0, k_mu=k,
                          k_lambda=k, k_damp=2.0e-3 * k, tri_ke=0.0, tri_ka=0.0, tri_kd=0.0, edge_ke=1.0e-2,
                          edge_kd=1.0e-5, particle_radius=0.035)
    return list(range(start, builder.particle_count))


def _c04_soft_collider_meshes(model, soft_ids: np.ndarray, nworld: int) -> list[wp.Mesh]:
    """One surface mesh per world over that world's soft particles (example_vbd_mpm_coupled_solver.py:300-318)."""
    tri = model.tri_indices.numpy().reshape(-1, 3)
    per = len(soft_ids) // nworld
    meshes = []
    q = model.particle_q.numpy()
    for w in range(nworld):
        ids = soft_ids[w * per:(w + 1) * per]
        local = {int(pid): i for i, pid in enumerate(ids)}
        idx = [local[int(v)] for t in tri if all(int(v) in local for v in t) for v in t]
        if not idx:
            raise RuntimeError("soft body surface produced no collider triangles")
        meshes.append(wp.Mesh(points=wp.array(q[ids], dtype=wp.vec3, device=model.device),
                              indices=wp.array(idx, dtype=wp.int32, device=model.device),
                              velocities=wp.zeros(len(ids), dtype=wp.vec3, device=model.device)))
    return meshes


def _c04_scene(nworld: int, device: str, config: Config) -> Built:
    """XPBD particles or a VBD tet cube falling into an implicit-MPM bed (proxy), or one MPM for everything.

    Derived from newton/examples/multiphysics/example_xpbd_mpm_coupled_solver.py (xpbd) and
    example_vbd_mpm_coupled_solver.py (vbd, soft surface as an MPM mesh collider). params: mode (xpbd | vbd | mono).
    """
    p = config.params
    mode = p["mode"]
    tpl = newton.ModelBuilder()
    tpl.default_shape_cfg.mu = 0.35 if mode != "vbd" else 0.8
    SolverImplicitMPM.register_custom_attributes(tpl)
    c = C04_BED
    bed = _add_sand_block(tpl, c["lo"], c["hi"], c["voxel"], c["ppc"], c["density"], C04_BED_ATTRS,
                          jitter_frac=0.25 * 0.45 / 0.5, radius_frac=0.45)
    obj = _c04_soft_cube(tpl) if mode == "vbd" else _c04_xpbd_cluster(tpl, as_mpm=mode == "mono")
    npw = tpl.particle_count
    main = _replicate(tpl, nworld)
    SolverImplicitMPM.register_custom_attributes(main)
    main.add_ground_plane()
    main.color()
    model = main.finalize(device=device)
    bed_all, obj_all = np.asarray(_expand(bed, npw, nworld)), np.asarray(_expand(obj, npw, nworld))
    mpm_cfg = _mpm_config(c["voxel"], nworld, iterations=p.get("mpm_iterations", 40), padding=38,
                          cells_per_world=1 << 16, velocity_mode="forward" if mode == "vbd" else None)
    static_ids = None
    if mode == "mono":
        solver = SolverImplicitMPM(model, config=mpm_cfg)
        in_place, ledger_states = True, None
    elif mode == "xpbd":
        model.particle_mu = 0.25
        model.particle_cohesion = 0.0
        model.particle_adhesion = 0.0
        model.particle_max_velocity = p.get("particle_max_velocity", 18.0)
        model.soft_contact_ke = 5.0e4
        model.soft_contact_kd = 1.0e-2
        model.soft_contact_mu = 0.35
        solver = SolverCoupledProxy(
            model=model,
            entries=[SolverCoupled.Entry(name="xpbd", solver=lambda v: SolverXPBD(
                model=v, iterations=p.get("xpbd_iterations", 8), soft_contact_relaxation=0.55),
                particles=obj_all.tolist()),
                SolverCoupled.Entry(name="mpm", solver=lambda v: SolverImplicitMPM(model=v, config=mpm_cfg),
                                    particles=bed_all.tolist(), in_place=True)],
            coupling=SolverCoupledProxy.Config(
                iterations=p.get("proxy_iterations", 3),
                proxies=[SolverCoupledProxy.Proxy(source="xpbd", destination="mpm", particles=obj_all.tolist(),
                                                  mass_scale=p.get("mass_scale", 0.15), mode="lagged")]))
        in_place = False
    else:
        model.soft_contact_ke = 5.0e4
        model.soft_contact_kd = 1.0e-3 * model.soft_contact_ke
        model.soft_contact_mu = 0.8
        solver = SolverCoupledProxy(
            model=model,
            entries=[SolverCoupledProxy.Entry(name="vbd", solver=lambda v: SolverVBD(
                model=v, iterations=p.get("vbd_iterations", 8), particle_enable_tile_solve=True,
                particle_enable_self_contact=False), particles=obj_all.tolist()),
                SolverCoupledProxy.Entry(name="mpm", solver=lambda v: SolverImplicitMPM(model=v, config=mpm_cfg),
                                         particles=bed_all.tolist())],
            coupling=SolverCoupledProxy.Config(
                iterations=p.get("proxy_iterations", 3),
                proxies=[SolverCoupledProxy.Proxy(source="vbd", destination="mpm", particles=obj_all.tolist(),
                                                  proxy_particles=obj_all.tolist(),
                                                  mass_scale=p.get("mass_scale", 0.5), mode="lagged")]))
        meshes = _c04_soft_collider_meshes(model, obj_all, nworld)
        per = len(obj_all) // nworld
        solver.solver("mpm").setup_collider(
            collider_meshes=[*meshes, None], collider_body_ids=[*([None] * nworld), -1],
            collider_margins=[*([0.025] * nworld), None], collider_friction=[*([0.6] * nworld), 0.8],
            collider_particle_ids=[*[obj_all[w * per:(w + 1) * per].tolist() for w in range(nworld)], None],
            collider_world_ids=[*range(nworld), -1], model=solver.view("mpm"))
        static_ids = [nworld]  # the ground plane is the last collider
        in_place = False
    s0 = model.state()
    s1 = s0 if in_place else model.state()
    control = model.control()
    if mode == "mono":
        pipeline, contacts = None, None
        mpm, states = solver, (lambda: [s0])
    else:
        pipeline = newton.CollisionPipeline(solver.view("xpbd") if mode == "xpbd" else model)
        contacts = pipeline.contacts()
        mpm = solver.solver("mpm")
        states = lambda: [solver.entry_state("mpm", "input"), solver.entry_state("mpm", "output")]  # noqa: E731
    ledger = _StaticImpulseLedger(mpm, states, device, static_ids)
    iface = _ImpulseIntegrator((lambda: None) if mode == "mono" else (lambda: _proxy_force_array(solver, "particle")),
                               obj_all, device)

    def post_substep(b: Built, dt: float) -> None:
        b.extra["ledger"].accumulate()
        b.extra["iface"].accumulate(dt)

    return Built(model, solver, s0, s1, control, contacts, pipeline, nworld=nworld,
                 extra={"in_place": in_place, "bed": bed_all, "obj": obj_all, "ledger": ledger, "iface": iface,
                        "obj_in_mpm": mode == "mono",
                        "post_substep": post_substep,
                        "energy_law": "creation" if mode == "vbd" else "tick"})


class ParticlesIntoMPM(_CoupledScenario):
    """C04: momentum ledger within 1 %, bed support at rest within 2 %, no particle below the floor."""

    id = "C04_particles_into_mpm"
    title = "XPBD particles / a VBD tet cube falling into an implicit-MPM granular bed (proxy) vs monolithic MPM"
    horizon_s = 2.0
    accuracy_unit = "%"
    accuracy_ref = "|dP - (M g T + J_floor)| / (|M g| T): momentum ledger over the timed window"
    ladder = (1, 16, 256, 1024)
    sample_every = 4
    rest_window_s = 0.5
    _F = 1.0 / 60.0
    configs = (
        Config("mono_mpm", "implicit_mpm", dt=_F, substeps=2, params={"mode": "mono"}, max_nworld=256),
        Config("proxy_xpbd_mpm", "proxy:xpbd+mpm", dt=_F, substeps=2, params={"mode": "xpbd"}, max_nworld=256),
        Config("proxy_vbd_mpm", "proxy:vbd+mpm", dt=_F, substeps=4, params={"mode": "vbd"}, max_nworld=256),
    )

    def _scene(self, nworld: int, device: str, config: Config) -> Built:
        return _c04_scene(nworld, device, config)

    def _momentum(self, b: Built) -> np.ndarray:
        qd = b.state_0.particle_qd.numpy().astype(np.float64)
        return (b.model.particle_mass.numpy().astype(np.float64)[:, None] * qd).sum(axis=0)

    def on_start(self, b: Built, rec: dict) -> None:
        b.extra.update(p0=self._momentum(b), t0=self.sim_time(b), j0=b.extra["ledger"].value(), fz=[], jz=[],
                       escaped=0, obj_floor=False)

    def measure(self, b: Built, t: float, rec: dict) -> None:
        super().measure(b, t, rec)
        q = b.state_0.particle_q.numpy()
        b.extra["escaped"] = max(b.extra["escaped"], int(np.sum(q[:, 2] < 0.0)))
        r = b.model.particle_radius.numpy()
        obj = b.extra["obj"]
        if np.any(q[obj, 2] < r[obj] + 0.002):
            b.extra["obj_floor"] = True  # object reached the floor: its floor impulse is not ledgered
        if b.extra["iface"].available:
            b.extra["fz"].append((t, b.extra["iface"].value()[:, 2].reshape(b.nworld, -1).sum(axis=1)))
        b.extra["jz"].append((t, b.extra["ledger"].value()))

    def finish(self, b: Built, rec: dict) -> None:
        super().finish(b, rec)
        model = b.model
        g = _gravity(model)
        gn = float(np.linalg.norm(g))
        pm = model.particle_mass.numpy().astype(np.float64)
        mass, m_obj = float(pm.sum()), float(pm[b.extra["obj"]].sum())
        t_end = self.sim_time(b)
        ledger = _ledger_residual(b.extra["p0"], self._momentum(b), b.extra["ledger"].value() - b.extra["j0"], mass,
                                  g, t_end - b.extra["t0"], m_obj)
        t0 = t_end - self.rest_window_s
        fz = _mean_force(b.extra["fz"], t0, t_end)  # per world: interface force on the object [N]
        w_obj = m_obj * gn / b.nworld
        iface = float(np.max(np.abs(fz - w_obj)) / w_obj * 100.0) if fz is not None else None
        jwin = _window(b.extra["jz"], t0, t_end)
        floor = None
        if len(jwin) >= 2:
            dj = (jwin[-1][1][2] - jwin[0][1][2]) / max(jwin[-1][0] - jwin[0][0], 1e-12)
            floor = abs(dj - mass * gn) / (mass * gn) * 100.0
        support = iface if iface is not None else floor
        m = rec["metrics"]
        m.update(**ledger, support_err_pct=support, interface_support_err_pct=iface, floor_support_err_pct=floor,
                 escaped=b.extra["escaped"], ledger_object_floor_contact=b.extra["obj_floor"],
                 # monolithic: the object is MPM material, so its floor impulse is in J_floor already
                 law_pass=bool(ledger["momentum_residual_pct"] <= 1.0 and support is not None and support <= 2.0
                               and b.extra["escaped"] == 0 and (b.extra["obj_in_mpm"] or not b.extra["obj_floor"])
                               and m["energy_ok"]))
        rec["accuracy_error"] = ledger["momentum_residual_pct"]


