def _c05_rigid_on_deformable(nworld: int, device: str, config: Config) -> Built:
    """Rigid boxes + pendulum chain on cloth (+ soft grids for VBD); proxy rigid+deformable or monolithic.

    Derived from newton/examples/multiphysics/example_mujoco_vbd_coupled_solver.py and
    example_mujoco_xpbd_coupled_solver.py (their --solver vbd / xpbd baselines are the monolithic configs).
    params: deform (vbd | xpbd), mode (proxy | mono), rigid (mujoco | kamino), body_mass_scale (mass ratio test).
    """
    p = config.params
    deform, mode = p["deform"], p["mode"]
    rigid_kind = p.get("rigid", "mujoco")
    tpl = newton.ModelBuilder()
    if deform == "vbd":
        tpl.default_shape_cfg.ke = 2.0e4
    if rigid_kind == "kamino":
        SolverKamino.register_custom_attributes(tpl)
    _c05_rigid_boxes(tpl, deform)
    (_c05_vbd_chain if deform == "vbd" else _c05_xpbd_chain)(tpl)
    rigid_per_world = tpl.body_count
    _c05_cloth(tpl, deform)
    if deform == "vbd":
        _c05_soft(tpl)
    main = _replicate(tpl, nworld)
    if rigid_kind == "kamino":
        SolverKamino.register_custom_attributes(main)
    main.add_ground_plane()
    main.color()
    model = main.finalize(device=device)
    scale = float(p.get("body_mass_scale", 1.0))
    if scale != 1.0:
        _scale_body_mass(model, np.arange(model.body_count), scale)
    if deform == "vbd":
        model.soft_contact_ke = 1.0e5
        model.soft_contact_mu = 0.5
        deform_kw = dict(iterations=p.get("vbd_iterations", 10), friction_epsilon=0.01,
                         particle_enable_self_contact=True, particle_self_contact_margin=0.01,
                         particle_self_contact_gap=0.0)
        deform_factory = lambda v: SolverVBD(model=v, **deform_kw)  # noqa: E731
    else:
        model.soft_contact_ke = 1.0e2
        model.soft_contact_kd = 1.0
        deform_kw = dict(iterations=p.get("xpbd_iterations", 40))
        deform_factory = lambda v: SolverXPBD(model=v, **deform_kw)  # noqa: E731
    rigid = _expand(range(rigid_per_world), tpl.body_count, nworld)
    if mode == "mono":
        solver = deform_factory(model)
    else:
        mj_kw = {"use_mujoco_contacts": False, "njmax": 300 * nworld, "nconmax": 200 * nworld}
        rname, rfactory = _rigid_entry(rigid_kind, mj_kw)
        others = sorted(set(range(model.body_count)) - set(rigid))
        solver = SolverCoupledProxy(
            model=model,
            entries=[SolverCoupledProxy.Entry(name=rname, solver=rfactory, bodies=rigid,
                                              joints=list(range(model.joint_count))),
                     SolverCoupledProxy.Entry(name=deform, solver=deform_factory, bodies=others,
                                              particles=list(range(model.particle_count)))],
            coupling=SolverCoupledProxy.Config(
                proxies=[SolverCoupledProxy.Proxy(
                    source=rname, destination=deform, bodies=rigid, mass_scale=p.get("mass_scale", 1.0),
                    mode=p.get("coupling_mode", "lagged"),
                    collision_pipeline=(lambda m: newton.CollisionPipeline(m, broad_phase="explicit"))
                    if deform == "vbd" else None,
                    collide_interval=1 if deform == "vbd" else None)],
                iterations=p.get("proxy_iterations", 1)))
    s0, s1, control = model.state(), model.state(), model.control()
    newton.eval_fk(model, model.joint_q, model.joint_qd, s0)
    pipeline = newton.CollisionPipeline(model)
    contacts = pipeline.contacts()
    track = np.asarray(rigid[:rigid_per_world])
    return Built(model, solver, s0, s1, control, contacts, pipeline, nworld=nworld,
                 extra={"collide_once": deform == "vbd", "traj_bodies": track, "rigid_bodies": np.asarray(rigid),
                        "energy_law": "creation"})


def _scale_body_mass(model, ids: np.ndarray, scale: float) -> None:
    """Scale mass and inertia of the given bodies in place (before solvers are created)."""
    for name, f in (("body_mass", scale), ("body_inv_mass", 1.0 / scale), ("body_inertia", scale),
                    ("body_inv_inertia", 1.0 / scale)):
        arr = getattr(model, name).numpy()
        arr[ids] = arr[ids] * f
        getattr(model, name).assign(arr)


def _quat_from_x_axis(direction: np.ndarray) -> wp.quat:
    d = np.asarray(direction, dtype=np.float64)
    d = d / np.linalg.norm(d)
    axis = np.cross([1.0, 0.0, 0.0], d)
    w = 1.0 + d[0]
    if w < 1e-6:
        axis, w = np.array([0.0, 1.0, 0.0]), 0.0
    q = np.array([*axis, w])
    q /= np.linalg.norm(q)
    return wp.quat(*[float(x) for x in q])


def _fourbar_template(mass_scale: float) -> tuple[newton.ModelBuilder, dict]:
    """Closed four-bar of example_kamino_mujoco_admm_solver.py:150-255 (two links per solver)."""
    b = newton.ModelBuilder(gravity=(0.0, 0.0, -9.81))
    SolverKamino.register_custom_attributes(b)
    lb, rb = np.array([-0.48, 0.0, 1.05]), np.array([0.48, 0.0, 1.05])
    lt, rt = np.array([-0.30, 0.0, 1.55]), np.array([0.34, 0.0, 1.46])

    def bar(a, c, label, mass):
        axis = c - a
        length = float(np.linalg.norm(axis))
        inertia = wp.mat33(np.eye(3, dtype=np.float32) * max(mass, 1e-3) * length * length / 12.0)
        body = b.add_link(xform=wp.transform(p=wp.vec3(*(0.5 * (a + c))), q=_quat_from_x_axis(axis)), mass=mass,
                          inertia=inertia, label=label)
        b.add_shape_box(body, hx=0.5 * length, hy=0.035, hz=0.035)
        return body, np.array([-0.5 * length, 0, 0], np.float32), np.array([0.5 * length, 0, 0], np.float32)

    ground, g_l, g_r = bar(lb, rb, "mujoco_ground_link", 0.0)
    jg = b.add_joint_fixed(parent=-1, child=ground, parent_xform=wp.transform(p=wp.vec3(*(0.5 * (lb + rb))),
                                                                               q=_quat_from_x_axis(rb - lb)))
    b.add_articulation([jg])
    crank, c_b, c_t = bar(lb, lt, "kamino_crank", 0.35 * mass_scale)
    jc = b.add_joint_free(child=crank)
    b.add_articulation([jc])
    coupler, k_l, k_r = bar(lt, rt, "mujoco_coupler", 0.42)
    jk = b.add_joint_free(child=coupler)
    b.add_articulation([jk])
    rocker, r_b, r_t = bar(rb, rt, "kamino_rocker", 0.36 * mass_scale)
    jr = b.add_joint_free(child=rocker)
    b.add_articulation([jr])
    loop = []
    for parent, pp, child, cp in ((ground, g_l, crank, c_b), (crank, c_t, coupler, k_l),
                                  (coupler, k_r, rocker, r_t), (rocker, r_b, ground, g_r)):
        loop.append(b.add_joint_revolute(parent=parent, child=child, axis=wp.vec3(0.0, 1.0, 0.0), friction=0.001,
                                         parent_xform=wp.transform(p=wp.vec3(*pp), q=wp.quat_identity()),
                                         child_xform=wp.transform(p=wp.vec3(*cp), q=wp.quat_identity()),
                                         collision_filter_parent=True))
    ids = {"kamino_bodies": [crank, rocker], "kamino_joints": [jc, jr], "mujoco_bodies": [ground, coupler],
           "mujoco_joints": [jg, jk], "loop_joints": loop}
    return b, ids


