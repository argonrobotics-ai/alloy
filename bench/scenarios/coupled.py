@wp.kernel
def _increment_kernel(counter: wp.array(dtype=int)):
    counter[0] = counter[0] + 1


@wp.kernel
def _body_energy_kernel(
    ids: wp.array(dtype=int),
    body_q: wp.array(dtype=wp.transform),
    body_qd: wp.array(dtype=wp.spatial_vector),
    mass: wp.array(dtype=float),
    inertia: wp.array(dtype=wp.mat33),
    com: wp.array(dtype=wp.vec3),
    world: wp.array(dtype=int),
    g: wp.vec3,
    out: wp.array(dtype=wp.float64),
):
    b = ids[wp.tid()]
    X = body_q[b]
    v = wp.spatial_top(body_qd[b])
    w_body = wp.quat_rotate_inv(wp.transform_get_rotation(X), wp.spatial_bottom(body_qd[b]))
    m = mass[b]
    ke = 0.5 * m * wp.dot(v, v) + 0.5 * wp.dot(w_body, inertia[b] * w_body)
    pe = -m * wp.dot(g, wp.transform_point(X, com[b]))
    wp.atomic_add(out, wp.max(world[b], 0), wp.float64(ke + pe))


@wp.kernel
def _particle_energy_kernel(
    ids: wp.array(dtype=int),
    q: wp.array(dtype=wp.vec3),
    qd: wp.array(dtype=wp.vec3),
    mass: wp.array(dtype=float),
    world: wp.array(dtype=int),
    g: wp.vec3,
    out: wp.array(dtype=wp.float64),
):
    p = ids[wp.tid()]
    m = mass[p]
    v = qd[p]
    wp.atomic_add(out, wp.max(world[p], 0), wp.float64(0.5 * m * wp.dot(v, v) - m * wp.dot(g, q[p])))


@wp.kernel
def _energy_event_kernel(
    e_now: wp.array(dtype=wp.float64),
    e_prev: wp.array(dtype=wp.float64),
    armed: wp.array(dtype=int),
    counter: wp.array(dtype=int),
    k0: int,
    k1: int,
    threshold: wp.float64,
    events: wp.array(dtype=int),
    max_gain: wp.array(dtype=wp.float64),
    e_max: wp.array(dtype=wp.float64),
):
    w = wp.tid()
    k = counter[0]
    if armed[0] != 0 and k >= k0 and k < k1:
        gain = e_now[w] - e_prev[w]
        if gain > threshold:
            events[w] = events[w] + 1
        max_gain[w] = wp.max(max_gain[w], gain)
    e_max[w] = wp.max(e_max[w], e_now[w])
    e_prev[w] = e_now[w]


@wp.kernel
def _arm_kernel(armed: wp.array(dtype=int)):
    armed[0] = 1


@wp.kernel
def _accumulate_static_impulse_kernel(
    impulses: wp.array(dtype=wp.vec3),
    collider_ids: wp.array(dtype=int),
    is_static: wp.array(dtype=int),
    out: wp.array(dtype=wp.float64),
):
    i = wp.tid()
    cid = collider_ids[i]
    if cid < 0 or cid >= is_static.shape[0]:
        return
    if is_static[cid] == 0:
        return
    f = impulses[i]
    wp.atomic_add(out, 0, wp.float64(f[0]))
    wp.atomic_add(out, 1, wp.float64(f[1]))
    wp.atomic_add(out, 2, wp.float64(f[2]))


@wp.kernel
def _apply_target_row_kernel(
    table: wp.array2d(dtype=float),
    counter: wp.array(dtype=int),
    stride: int,
    target: wp.array(dtype=float),
):
    w, j = wp.tid()
    row = wp.min(counter[0], table.shape[0] - 1)
    target[w * stride + j] = table[row, j]


