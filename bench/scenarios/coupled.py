    def _scene(self, nworld: int, device: str, config: Config) -> Built:
        return _c01_scene(nworld, device, config)

    def _frames(self, b: Built) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
        """(hand pos, hand quat, mid-segment COM, payload COMs) per world, float64."""
        q = b.state_0.body_q.numpy().astype(np.float64)
        hand = q[b.extra["hand_all"]]
        pay = _body_com_world(b.model, q, b.extra["payload_all"]).reshape(b.nworld, b.extra["payload_n"], 3)
        return hand[:, :3], hand[:, 3:7], pay[:, b.extra["mid"]], pay

    def on_start(self, b: Built, rec: dict) -> None:
        pm = b.model.body_mass.numpy().astype(np.float64)[b.extra["payload_all"]].reshape(b.nworld, -1)
        b.extra.update(payload_mass=pm.sum(axis=1), slip_ref=None, slip=np.zeros(b.nworld),
                       hold_slip=np.zeros(b.nworld), lift=np.full(b.nworld, -np.inf), pz=[],
                       hold_clear=np.full(b.nworld, np.inf), mid_z0=self._frames(b)[2][:, 2].copy())

    def measure(self, b: Built, t: float, rec: dict) -> None:
        super().measure(b, t, rec)
        ph = b.extra["phases"]
        hp, hq, mid, pay = self._frames(b)
        tcp = hp + M.quat_rotate(hq, np.array([0.0, 0.0, C01_TCP_OFFSET]))
        rel = M.quat_rotate(hq * np.array([-1.0, -1.0, -1.0, 1.0]), mid - tcp)  # mid segment in the hand frame
        g0, g1 = ph["grasp"][1], ph["carry"][1]
        if g0 - 1e-9 <= t <= g1 + 1e-9:
            if b.extra["slip_ref"] is None:
                b.extra["slip_ref"] = rel.copy()
            d = np.linalg.norm(rel - b.extra["slip_ref"], axis=1) * 1e3
            b.extra["slip"] = np.maximum(b.extra["slip"], d)
            if t <= ph["hold"][1] + 1e-9:
                b.extra["hold_slip"] = np.maximum(b.extra["hold_slip"], d)
        h0, h1 = ph["hold"][0] + C01_HOLD_SETTLE_S, ph["hold"][1]
        if h0 - 1e-9 <= t <= h1 + 1e-9:
            b.extra["lift"] = np.maximum(b.extra["lift"], mid[:, 2] - b.extra["mid_z0"])
            clear = pay[:, :, 2].min(axis=1) - b.extra["surface_z"] - b.extra["radius"]
            b.extra["hold_clear"] = np.minimum(b.extra["hold_clear"], clear)
            qd = b.state_0.body_qd.numpy().astype(np.float64)[b.extra["payload_all"], 2].reshape(b.nworld, -1)
            pmass = b.model.body_mass.numpy().astype(np.float64)[b.extra["payload_all"]].reshape(b.nworld, -1)
            b.extra["pz"].append((t, (pmass * qd).sum(axis=1)))
        b.extra["mid_last"] = mid
        b.extra["t_end"] = t

    def finish(self, b: Built, rec: dict) -> None:
        super().finish(b, rec)
        ph, nw = b.extra["phases"], b.nworld
        gn = float(np.linalg.norm(_gravity(b.model)))
        W = b.extra["payload_mass"] * gn
        k0, k1 = b.extra["hold_k"]
        steps = int(b.extra["counter"].numpy()[0])
        T = (min(steps, k1) - k0) * b.extra["cfg"].dt
        m = rec["metrics"]
        fb = rec_err = None
        if T > 0 and b.extra.get("force_src"):
            F = b.extra["impulse"].numpy() / T  # time-averaged interface force on the gripper [N]
            fb = np.abs(-F[:, 2] - W) / W * 100.0
            rec_err = float(np.max(fb))
            m.update(gripper_force_z_n=F[:, 2].tolist(), force_balance_per_world_pct=fb.tolist())
        if T > 0 and b.extra.get("force_src_arm"):
            Fa = b.extra["impulse_arm"].numpy() / T  # same, summed over every arm body
            m.update(arm_force_z_n=Fa[:, 2].tolist(),
                     arm_force_balance_err_pct=float(np.max(np.abs(-Fa[:, 2] - W) / W * 100.0)))
        win = b.extra["pz"]
        pay_err = None
        if len(win) >= 2:  # payload-side cross-check: R_z = dP_z/dt + W from the payload's own momentum
            ts = [t for t, _ in win]
            slope = np.array([_slope(ts, [v[w] for _, v in win]) for w in range(nw)])
            pay_err = float(np.max(np.abs(slope) / W * 100.0))
        hold_done = T >= (k1 - k0) * b.extra["cfg"].dt - 1e-9
        t_end = b.extra.get("t_end", 0.0)
        place = None
        if t_end >= ph["release"][1] - 1e-9:
            place = np.linalg.norm(b.extra["mid_last"][:, :2] - np.asarray(C01_PLACE_XY), axis=1) * 1e3
        lifted = b.extra["lift"] > 0.10
        slip_mm = float(np.max(b.extra["slip"])) if b.extra["slip_ref"] is not None else None
        clear_ok = bool(np.all(b.extra["hold_clear"] > 1.0e-3)) if hold_done else None
        success = (lifted & (place <= 10.0)) if place is not None else None
        m.update(force_balance_err_pct=rec_err, hold_window_s=[ph["hold"][0] + C01_HOLD_SETTLE_S, ph["hold"][1]],
                 hold_window_complete=hold_done, payload_weight_n=W.tolist(), payload_reaction_err_pct=pay_err,
                 hold_ground_clear=clear_ok,
                 hold_min_clearance_mm=(float(np.min(b.extra["hold_clear"])) * 1e3 if hold_done else None),
                 slip_mm=slip_mm, hold_slip_mm=float(np.max(b.extra["hold_slip"])) if slip_mm is not None else None,
                 lift_mm=(float(np.min(b.extra["lift"])) * 1e3 if hold_done else None),
                 place_err_mm=float(np.max(place)) if place is not None else None,
                 success_rate=float(np.mean(success)) if success is not None else None,
                 timeline_s={k: list(v) for k, v in ph.items()},
                 interface_force_source=("proxy coupling_forces" if getattr(b.solver, "_proxy_mappings", None)
                                         else "admm body_f") if b.extra.get("force_src") else None)
        complete = hold_done and slip_mm is not None and t_end >= ph["carry"][1] - 1e-9
        m["law_pass"] = (bool(rec_err is not None and rec_err <= 2.0 and slip_mm <= 1.0 and clear_ok and m["energy_ok"])
                         if complete else None)
        m["law_window_reached"] = complete
        rec["accuracy_error"] = rec_err


