def _gravity(model) -> np.ndarray:
    return np.asarray(model.gravity.numpy(), dtype=np.float64).reshape(-1, 3)[0]


def _ids(values: Sequence[int] | np.ndarray, device) -> wp.array:
    return wp.array(np.asarray(values, dtype=np.int32), dtype=int, device=device)


def _expand(ids: Sequence[int], stride: int, nworld: int) -> list[int]:
    """Template-local ids -> ids in all replicated worlds (ModelBuilder.replicate keeps world blocks contiguous)."""
    return [w * stride + i for w in range(nworld) for i in ids]


def _replicate(template: newton.ModelBuilder, nworld: int, **builder_kw) -> newton.ModelBuilder:
    main = newton.ModelBuilder(**builder_kw)
    for attr in ("rigid_gap",):
        if hasattr(template, attr):
            setattr(main, attr, getattr(template, attr))
    main.replicate(template, copy_count=nworld)
    return main


def _kamino_config(max_iterations: int = 120) -> SolverKamino.Config:
    """The Kamino setup every coupled example uses (e.g. example_mujoco_mpm_coupled_solver.py:43-55)."""
    c = SolverKamino.Config()
    c.use_collision_detector = False
    c.use_fk_solver = False
    c.dynamics.preconditioning = True
    c.padmm.max_iterations = max_iterations
    c.padmm.primal_tolerance = 1.0e-5
    c.padmm.dual_tolerance = 1.0e-5
    c.padmm.compl_tolerance = 1.0e-5
    c.padmm.rho_0 = 0.1
    c.padmm.use_acceleration = True
    c.padmm.warmstart_mode = "containers"
    return c


def _rigid_entry(kind: str, mujoco_kw: dict, kamino_iters: int = 120) -> tuple[str, Callable]:
    if kind == "mujoco":
        return "mjc", lambda v: SolverMuJoCo(model=v, **mujoco_kw)
    if kind == "kamino":
        cfg = _kamino_config(kamino_iters)
        return "kamino", lambda v: SolverKamino(model=v, config=cfg)
    raise ValueError(f"unknown rigid solver {kind!r}")


def _body_com_world(model, body_q: np.ndarray, ids: np.ndarray) -> np.ndarray:
    return M.transform_points(body_q, ids, model.body_com.numpy()[ids])


def joint_gaps_mm(model, body_q: np.ndarray, joint_ids: np.ndarray | None = None) -> np.ndarray:
    """Anchor separation [mm] of revolute, ball and fixed joints: |X_parent * p_parent - X_child * p_child|.

    These joint types pin the two anchor points together, so any distance is a constraint violation (the S2
    joint-separation limit). Works for joints owned by one solver and for cross-solver joints that a coupler turns
    into attachments.
    """
    jt = model.joint_type.numpy()
    sel = np.isin(jt, (int(newton.JointType.REVOLUTE), int(newton.JointType.BALL), int(newton.JointType.FIXED)))
    if joint_ids is not None:
        mask = np.zeros_like(sel)
        mask[joint_ids] = True
        sel &= mask
    idx = np.nonzero(sel)[0]
    if idx.size == 0:
        return np.zeros(0)
    parent = model.joint_parent.numpy()[idx]
    child = model.joint_child.numpy()[idx]
    xp = model.joint_X_p.numpy()[idx][:, :3]
    xc = model.joint_X_c.numpy()[idx][:, :3]
    a = M.transform_points(body_q, parent, xp)
    c = M.transform_points(body_q, child, xc)
    return np.linalg.norm(a - c, axis=1) * 1e3


def _slope(t: Sequence[float], y: Sequence[float]) -> float:
    """Least-squares slope dy/dt (0 for fewer than two samples)."""
    t = np.asarray(t, dtype=np.float64)
    y = np.asarray(y, dtype=np.float64)
    if t.size < 2 or np.ptp(t) == 0:
        return 0.0
    return float(np.polyfit(t, y, 1)[0])


def _contact_overflow(contacts) -> int:
    """1 when the last collision pass dropped contacts (count above capacity or reducer overflow)."""
    if contacts is None or getattr(contacts, "contact_counters", None) is None:
        return 0
    c = contacts.contact_counters.numpy()
    rigid_over = int(c[0]) > int(getattr(contacts, "rigid_contact_max", 1 << 30))
    soft_over = int(c[1]) > int(getattr(contacts, "soft_contact_max", 1 << 30) or (1 << 30))
    return int(rigid_over or soft_over or int(c[2]) != 0)


def _window(samples: list[tuple[float, Any]], t0: float, t1: float) -> list[tuple[float, Any]]:
    return [(t, v) for t, v in samples if t0 - 1e-9 <= t <= t1 + 1e-9]


def _finite_or_none(x: float | None) -> float | None:
    return None if x is None or not np.isfinite(x) else float(x)


# ---- reference store (coupled-vs-monolithic comparisons) --------------------------------------------
def _ref_key(scenario: str, config: str, rec: dict) -> tuple:
    return (scenario, config, rec["nworld"], rec["device"], round(float(rec["horizon_s"]), 6))


def _store_ref(scenario: str, rec: dict, payload: dict) -> None:
    _REF_CACHE[_ref_key(scenario, rec["config"], rec)] = payload


def _load_ref(scenario: str, ref_config: str, rec: dict) -> dict | None:
    """Reference metrics from this process, else the latest ok row of the same rung in the results file."""
    hit = _REF_CACHE.get(_ref_key(scenario, ref_config, rec))
    if hit is not None:
        return hit
    path = RESULTS / f"{scenario}.jsonl"
    if not path.exists():
        return None
    want = _ref_key(scenario, ref_config, rec)
    found = None
    for line in path.read_text().splitlines():
        try:
            r = json.loads(line)
        except json.JSONDecodeError:
            continue
        if r.get("status") != "ok" or r.get("config") != ref_config or not r.get("stable"):
            continue
        if _ref_key(scenario, ref_config, r) == want:
            found = r.get("metrics", {}).get("ref_payload")
    return found


def _traj_dev_mm(traj: dict | None, ref: dict | None) -> float | None:
    """Max over samples and bodies of |p - p_ref| [mm]; ref interpolated onto this run's sample times."""
    if not traj or not ref or not traj["t"] or not ref.get("t"):
        return None
    p = np.asarray(traj["pos_mm"], dtype=np.float64)
    pr = np.asarray(ref["pos_mm"], dtype=np.float64)
    if p.shape[1:] != pr.shape[1:]:
        return None
    t, tr = np.asarray(traj["t"]), np.asarray(ref["t"])
    keep = (t >= tr[0] - 1e-9) & (t <= tr[-1] + 1e-9)
    if not np.any(keep):
        return None
    interp = np.empty_like(p[keep])
    for b in range(p.shape[1]):
        for k in range(3):
            interp[:, b, k] = np.interp(t[keep], tr, pr[:, b, k])
    return float(np.max(np.linalg.norm(p[keep] - interp, axis=2)))


