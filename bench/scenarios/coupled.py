class _CoupledScenario(Scenario):
    """Shared stepping and bookkeeping for the coupled family.

    b.extra keys a scene builder may set:
      collide_once     collide once per outer step instead of every substep (examples that do so)
      in_place         solver steps state_0 -> state_0 (MPM-owned scenes)
      eval_ik          newton.eval_ik on the output state after each substep (ADMM examples)
      energy_bodies / energy_particles   index sets for the energy ledger (default: all)
      pre_step(b)      device-side scripted control before the substeps (no host sync)
      post_substep(b, dt)   device-side bookkeeping after each substep (e.g. MPM floor impulse)
    """

    family = FAMILY

    def build(self, nworld: int, device: str, config: Config) -> Built:
        b = self._scene(nworld, device, config)
        b.nworld = nworld
        b.extra["cfg"] = config
        b.extra["counter"] = wp.zeros(1, dtype=int, device=device)
        model = b.model
        bodies = b.extra.get("energy_bodies", np.arange(model.body_count))
        particles = b.extra.get("energy_particles", np.arange(model.particle_count))
        b.extra["energy"] = _EnergyTracker(model, nworld, bodies, particles, b.extra["counter"],
                                           window=b.extra.get("energy_window", (0, 1 << 30)))
        b.extra["energy"].prime(b.state_0)
        # Optional sub-ledgers {name: (bodies, particles, (k0, k1))}, e.g. the rigid side of a coupled pair alone, so a
        # gain can be attributed to the coupling or to one solver's own noise floor.
        b.extra["energy_more"] = {}
        for name, (eb, ep, win) in b.extra.get("energy_sets", {}).items():
            tr = _EnergyTracker(model, nworld, eb, ep, b.extra["counter"], window=win)
            tr.prime(b.state_0)
            b.extra["energy_more"][name] = tr
        b.extra["overflow"] = 0
        return b

    def _scene(self, nworld: int, device: str, config: Config) -> Built:
        raise NotImplementedError

    # ---- stepping ------------------------------------------------------------------------------------
    def step(self, b: Built, config: Config) -> None:
        pre = b.extra.get("pre_step")
        if pre is not None:
            pre(b)
        if b.extra.get("collide_once") and b.pipeline is not None:
            b.pipeline.collide(b.state_0, b.contacts)
        h = config.dt / config.substeps
        for _ in range(config.substeps):
            self.substep(b, h)
        wp.launch(_increment_kernel, dim=1, inputs=[b.extra["counter"]], device=b.model.device)
        b.extra["energy"].update(b.state_0)
        for tr in b.extra["energy_more"].values():
            tr.update(b.state_0)

    def substep(self, b: Built, dt: float) -> None:
        b.state_0.clear_forces()
        if b.pipeline is not None and not b.extra.get("collide_once"):
            b.pipeline.collide(b.state_0, b.contacts)
        if b.extra.get("in_place"):
            b.solver.step(b.state_0, b.state_0, b.control, b.contacts, dt)
        else:
            b.solver.step(b.state_0, b.state_1, b.control, b.contacts, dt)
            if b.extra.get("eval_ik"):
                newton.eval_ik(b.model, b.state_1, b.state_1.joint_q, b.state_1.joint_qd)
            b.state_0, b.state_1 = b.state_1, b.state_0
        post = b.extra.get("post_substep")
        if post is not None:
            post(b, dt)

    # ---- hooks ---------------------------------------------------------------------------------------
    blowup_speed = 50.0  # [m/s]; no scene here legitimately moves faster (drops are <= 3 m)

    def measure(self, b: Built, t: float, rec: dict) -> None:
        super().measure(b, t, rec)
        b.extra["overflow"] = max(b.extra["overflow"], _contact_overflow(b.contacts))
        b.extra["t_last"] = t
        vmax = 0.0
        for name in ("particle_qd", "body_qd"):
            arr = getattr(b.state_0, name, None)
            if arr is not None and arr.shape[0] > 0:
                v = arr.numpy()
                vmax = max(vmax, float(np.max(np.linalg.norm(v[:, :3], axis=1))))
        b.extra["vmax"] = max(b.extra.get("vmax", 0.0), vmax)
        if vmax > self.blowup_speed and "blowup_t" not in b.extra:
            b.extra["blowup_t"] = t

    def finish(self, b: Built, rec: dict) -> None:
        m = rec["metrics"]
        m["max_speed_m_s"] = b.extra.get("vmax")
        if "blowup_t" in b.extra:  # finite but exploded: the harness only catches NaN/Inf
            rec["stable"] = False
            rec["notes"] = (rec["notes"] + f" blow-up: speed > {self.blowup_speed} m/s at t={b.extra['blowup_t']:.3f} s"
                            ).strip()
        m.update(b.extra["energy"].results())
        for name, tr in b.extra["energy_more"].items():
            m.update({k.replace("energy_", f"energy_{name}_", 1): v for k, v in tr.results().items()})
        law = b.extra.get("energy_law", "tick")
        m["energy_law"] = law
        if law == "tick":
            m["energy_ok"] = m["energy_gain_events"] == 0
        else:
            m["energy_ok"] = m["energy_creation_mj"] is not None and m["energy_creation_mj"] <= ENERGY_TICK_J * 1e3
        m["contact_overflow"] = b.extra["overflow"]
        m["conditions_covered"] = True

    def energy(self, b: Built) -> float | None:
        if b.model.body_count == 0:
            return M.particle_energy(b.model, b.state_0)
        return M.rigid_energy(b.model, b.state_0) + M.particle_energy(b.model, b.state_0)

    def sim_time(self, b: Built) -> float:
        """Device step counter x dt (valid under CUDA graph replay, where Python step() is not called)."""
        return int(b.extra["counter"].numpy()[0]) * b.extra["cfg"].dt


