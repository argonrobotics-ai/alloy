"""The support everything stands on: the library table, a generated floor, or any static object card.

"table" is the library's ``table_top_plywood`` (1.2 m x 0.8 m x 18 mm plywood, static) with its top face at z = 0;
"floor" is a generated 3 m x 3 m static plywood slab (card ``compose_floor``) with its top at z = 0. A generated
card is returned as YAML text; the builder writes it next to the scene cards so the saved folder loads on its own.

Example::

    >>> sup = support("table", catalog)                       # doctest: +SKIP
    >>> sup.placed.pose[2], sup.cards                         # doctest: +SKIP
    (-0.009, {})
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

from alloy.compose import geom
from alloy.compose.body import Body
from alloy.compose.layout import Placed
from alloy.compose.spec import ComposeError

TABLE_CARD = "table_top_plywood"
FLOOR_CARD = "compose_floor"
FLOOR_HALF = (1.5, 1.5, 0.01)           # m, half extents of the generated floor slab
FLOOR_MATERIAL = "plywood_marine"
SUPPORTS = ("table", "floor")


@dataclass
class Support:
    """The placed support and any generated cards it needs (file stem -> YAML text)."""

    placed: Placed
    cards: dict[str, str] = field(default_factory=dict)


def support(kind: str, catalog) -> Support:
    """The support for ``kind`` ("table", "floor" or a static object card name), top face at z = 0.

    Example: ``support("floor", Catalog()).cards`` holds the generated floor card."""
    if kind == "floor":
        return _floor()
    name = TABLE_CARD if kind == "table" else kind
    if name not in catalog.entries:
        raise ComposeError(f"support {kind!r} is not 'table', 'floor' or an object card",
                           f"use one of {SUPPORTS}, or a static card such as {TABLE_CARD!r}", field="support")
    info = catalog.info(name)
    if not info.placeable or info.motion != "static":
        why = info.reason if not info.placeable else f"its motion is {info.motion!r}, not 'static'"
        raise ComposeError(f"{name} cannot be the support: {why}", "use 'table' or 'floor', and put movable "
                           f"containers on it as items (e.g. 'three nuts in a tray')", field="support")
    return Support(_at_zero(catalog.body(name), name))


def _at_zero(body: Body, card: str) -> Placed:
    top = float(body.vertices[:, 2].max())
    centre = (body.vertices[:, :2].max(axis=0) + body.vertices[:, :2].min(axis=0)) / 2
    return Placed(card, card, body, 0.0, np.array([-centre[0], -centre[1], -top]))


def _floor() -> Support:
    v, f = geom.primitive_mesh("box", FLOOR_HALF)
    body = Body.from_mesh(FLOOR_CARD, v, f, np.zeros(3))
    text = "\n".join([
        "# generated by alloy.compose: the floor slab the scene stands on (top face at z = 0)",
        "schema: alloy.object/1", f"name: {FLOOR_CARD}", "shape:", "  primitive:", "    kind: box",
        f"    size: [{FLOOR_HALF[0]}, {FLOOR_HALF[1]}, {FLOOR_HALF[2]}]", f"material: {FLOOR_MATERIAL}",
        "motion: static", ""])
    return Support(_at_zero(body, FLOOR_CARD), {FLOOR_CARD: text})


__all__ = ["FLOOR_CARD", "SUPPORTS", "Support", "TABLE_CARD", "support"]
