"""Turn batch outputs (``<out>/<name>/result.json`` + files) into the import library ``imports/ycb_gso/``.

Writes cards (``objects/<ycb|gso>/<name>.yaml``), effective materials (``materials/<ycb|gso>/<name>_eff.yaml``),
``manifest.json``, ``queue.jsonl`` (sourcing queue) and ``ATTRIBUTION.md``, and copies ``physics.obj`` and its hull sidecar
into ``meshes/<name>/`` so the cards load locally (``visual.glb`` and ``thumb.png`` go to the asset store only).
"""

from __future__ import annotations

import dataclasses
import json
import logging
import shutil
from pathlib import Path

from alloy.cards.library import CardLibrary
from alloy.importers.common import cards as cw
from alloy.importers.common import manifest as mf
from alloy.importers.common import queue as qu
from alloy.importers.common.checks import THIN, wall_records
from alloy.importers.common.errors import ImporterError
from alloy.importers.common.process import FILES, HULLS, PHYSICS, RESULT, hull_words
from alloy.importers.ycb_gso import gso, ycb
from alloy.importers.ycb_gso.specs import ObjectSpec, gso_spec, ycb_fits, ycb_spec

log = logging.getLogger("alloy.importers")

LIB = "ycb_gso"
GIT_IGNORE = "meshes/\n"
LOCAL_FILES = (PHYSICS, HULLS)


def collect_results(out_dirs: list[Path]) -> dict[str, Path]:
    """Object name -> its output folder; later folders win, folders without ``result.json`` are skipped.

    Example::

        collect_results([Path("jobs/az/gso_0/out"), Path("jobs/rerun/out")])
    """
    found: dict[str, Path] = {}
    for root in out_dirs:
        for d in sorted(Path(root).iterdir()):
            if (d / RESULT).is_file():
                found[d.name] = d
    return found


def object_specs(dirs: dict[str, Path]) -> list[tuple[ObjectSpec, dict, Path]]:
    """``(spec, result, folder)`` for every YCB and GSO object with a result.

    Example::

        specs = object_specs(collect_results([Path("out")]))
    """
    results = {n: json.loads((d / RESULT).read_text(encoding="utf-8")) for n, d in dirs.items()}
    fits = ycb_fits(results)
    lib = CardLibrary()
    out = []
    for o in ycb.OBJECTS:
        if o.card_name in results:
            out.append((ycb_spec(o, lib.material(o.material).density.value, fits), results[o.card_name],
                        dirs[o.card_name]))
    for name, d in dirs.items():
        if name.startswith("gso_"):
            spec = gso_spec(gso.read_metadata(d / gso.METADATA), results[name]["volume"], fits)
            if name not in (spec.name, gso.plain_card_name(spec_model(d))):
                raise ImporterError(name, "build", f"metadata gives card name {spec.name!r} but the batch output is "
                                                   f"{name!r}; fix gso.card_name or the metadata parser")
            out.append((spec, results[name], d))
    return out


def spec_model(d: Path) -> str:
    """The upstream model name in a batch output folder's metadata."""
    return gso.read_metadata(d / gso.METADATA).name


def _header(spec: ObjectSpec, result: dict) -> str:
    rel = f"meshes/{spec.name}"
    return "\n".join([
        f"generated by alloy.importers.ycb_gso from {spec.title}; do not edit, rerun the importer",
        f"geometry: {spec.attribution}; source: {spec.source_url}; licence: CC-BY-4.0; redistribute: yes",
        f"files: {rel}/physics.obj, {rel}/physics.hulls.obj ({hull_words(result.get('hulls', result))}), "
        f"{rel}/visual.glb "
        f"(glTF, +Y up), {rel}/thumb.png; get them with: python -m alloy.importers.ycb_gso fetch {spec.name}",
    ])


def _wall_pair(wall: float | tuple[float, float] | None) -> tuple[float | None, float | None]:
    """``(min_wall to declare, the validator probe's reading)`` from ``common.checks.wall_records`` or a bare value."""
    return wall if isinstance(wall, tuple) else (wall, wall)


def card_spec(spec: ObjectSpec, result: dict, wall: float | tuple[float, float] | None = None) -> cw.CardSpec:
    """The ``common.cards`` spec of one object (``wall``: ``(min_wall, probe reading)`` or a bare value).

    Example::

        cs = card_spec(spec, result)
    """
    wall, probe = _wall_pair(wall)
    return cw.CardSpec(name=spec.name, base_material=spec.material, material_note=spec.material_note,
                       mass=spec.mass, volume=result["volume"], mesh_path=f"meshes/{spec.name}/{PHYSICS}",
                       mesh_sha256=result["files"][PHYSICS], max_parts=result["n_hulls"],
                       header=_header(spec, result), min_wall=wall if wall is not None and wall < THIN else None,
                       min_wall_probe=probe)


STRONG_TAGS = ("DOC", "SNIPPET", "UNVERIFIED")       # alloy.sourcing tags that retire a queue row


def mass_tag(rec) -> str | None:
    """The sourcing tag of a record's mass (or density), or None without one.

    Example::

        mass_tag(load_records("ycb_gso").get("ycb_025_mug"))   # "DOC"
    """
    if rec is None:
        return None
    for f in ("mass", "effective_density", "density"):
        if f in rec.values:
            return rec.values[f].tag
    return None


def _mass_status(spec: ObjectSpec, tag: str | None) -> str:
    if tag in STRONG_TAGS:
        return "sourced"
    return "measured" if spec.mass.kind == "mass" else "estimate"


def _files(d: Path, result: dict) -> dict:
    """``{file: {"sha256", "bytes"}}`` for each output file: from the file when it is still on disk, else from the
    batch ``result.json`` (local copies already pushed to the store may be deleted to save disk)."""
    out = {}
    for f in FILES:
        if (d / f).is_file():
            out[f] = mf.file_entry(d / f)
        elif f in result.get("files", {}) and f in result.get("sizes", {}):
            out[f] = {"sha256": result["files"][f], "bytes": int(result["sizes"][f])}
    return out


def _manifest_entry(spec: ObjectSpec, result: dict, d: Path, wall: float | tuple[float, float], density: float,
                    tag: str | None) -> dict:
    wall, probe = _wall_pair(wall)
    entry = {"library": spec.library, "title": spec.title, "source": spec.source_url, "licence": "CC-BY-4.0",
            "attribution": spec.attribution, "card": f"objects/{spec.library}/{spec.name}.yaml",
            "material": f"materials/{spec.library}/{spec.name}{cw.EFF_SUFFIX}.yaml",
            "files": _files(d, result),
            "physics": {"volume": result["volume"], "faces": result["faces"], "n_hulls": result["n_hulls"],
                        "hull_volume_ratio": round(result["hulls"]["volume_ratio"], 4),
                        "repair": result["repair"]["method"], "simplify": result["repair"]["simplify"],
                        "mass_kg": round(density * result["volume"], 6), "mass_status": _mass_status(spec, tag),
                        "mass_tag": tag,
                        "texture": result["texture_ok"], "min_wall": wall,
                        "physics_sha256": result["files"][PHYSICS]}}
    if probe != wall:                                   # re-measured (common.walls): keep the probe's reading too
        entry["physics"]["min_wall_probe"] = probe
    return entry


MASS_FIELDS = ("mass", "effective_density", "density")


def _valid_with(cs: cw.CardSpec, base, rec) -> str:
    """"" if the record yields a material Alloy's validator accepts, else the first problem."""
    from alloy.cards.validate import validate_material  # noqa: PLC0415
    from alloy.sourcing import SourcingError  # noqa: PLC0415

    try:
        mat = cw.material_card(cs, base, rec)
    except (SourcingError, ValueError) as exc:
        return str(exc)
    errors = [i for i in validate_material(mat) if i.level == "error"]
    return f"{errors[0].field}: {errors[0].message}" if errors else ""


def _usable(cs: cw.CardSpec, base, rec):
    """The record, or only its mass when its other values break the material, or None (logged; estimate stays).

    A partial friction record can contradict the library values it keeps (mu_static from the record below the
    library's mu_dynamic); then only the mass is applied.
    """
    if rec is None:
        return None
    problem = _valid_with(cs, base, rec)
    if not problem:
        return rec
    mass_only = dataclasses.replace(rec, values={k: v for k, v in rec.values.items() if k in MASS_FIELDS})
    if mass_only.values and not _valid_with(cs, base, mass_only):
        log.warning("%s: sourcing record applied for mass only (%s)", cs.name, problem)
        return mass_only
    log.warning("%s: sourcing record not applied: %s", cs.name, problem)
    return None


def write_object(root: Path, spec: ObjectSpec, result: dict, d: Path, lib: CardLibrary,
                 wall: float | tuple[float, float], rec=None) -> dict:
    """Write one object's two cards (``rec``: its ``alloy.sourcing`` record or None) and local mesh files; returns
    its manifest entry.

    Example::

        entry = write_object(Path("imports/ycb_gso"), spec, result, Path("out/ycb_025_mug"), CardLibrary(), 2e-3)
    """
    cs, base = card_spec(spec, result, wall), lib.material(spec.material)
    given, rec = rec, _usable(cs, base, rec)
    obj_text, mat_text = cw.card_texts(cs, base, rec)
    density = cw.material_card(cs, base, rec).density.value
    for kind, suffix, text in (("objects", "", obj_text), ("materials", cw.EFF_SUFFIX, mat_text)):
        p = root / kind / spec.library / f"{spec.name}{suffix}.yaml"
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    mesh_dir = root / mf.MESH_DIR / spec.name
    mesh_dir.mkdir(parents=True, exist_ok=True)
    for f in LOCAL_FILES:
        shutil.copyfile(d / f, mesh_dir / f)
    entry = _manifest_entry(spec, result, d, wall, density, mass_tag(rec))
    entry["sourcing"] = None if rec is None else ("applied" if rec is given else "mass only")
    return entry


def _attribution(entries: dict) -> str:
    lines = ["# Attribution: imports/ycb_gso", "",
             "Every object here is a third-party scan licensed under Creative Commons Attribution 4.0 International",
             "(https://creativecommons.org/licenses/by/4.0/). Alloy changed each one: watertight remesh and",
             "simplification (physics.obj), CoACD convex decomposition (physics.hulls.obj), glTF re-export with",
             "JPEG textures (visual.glb), a rendered thumbnail, and estimated or measured mass and friction.", "",
             f"- YCB: {ycb.ATTRIBUTION}.", f"- GSO: {gso.ATTRIBUTION}.", "", "| Card | Source title | Source |",
             "|---|---|---|"]
    lines += [f"| {n} | {e['title']} | {e['source']} |" for n, e in sorted(entries.items())]
    return "\n".join(lines) + "\n"


THUMBS = "thumbs.json"


def apply_thumbs(root: Path, man: dict) -> int:
    """Use the thumbnails listed in ``thumbs.json`` (re-renders uploaded to the store by the camera work): their
    ``sha256`` and ``bytes`` replace each object's ``thumb.png`` entry. Returns how many entries changed.

    ``thumbs.json``: ``{"objects": {"<card>": {"sha256": "...", "bytes": N, ...}}}``.

    Example::

        apply_thumbs(Path("imports/ycb_gso"), manifest)
    """
    p = Path(root) / THUMBS
    if not p.is_file():
        return 0
    data = json.loads(p.read_text(encoding="utf-8"))
    n = 0
    for name, t in (data.get("objects", data)).items():
        files = man["objects"].get(name, {}).get("files")
        if files is not None and isinstance(t, dict) and "sha256" in t and "bytes" in t:
            files["thumb.png"] = {"sha256": t["sha256"], "bytes": int(t["bytes"])}
            n += 1
    return n


def prune(root: Path, man: dict, keep: set[str]) -> list[str]:
    """Remove manifest entries, cards, materials and queue rows of objects not in ``keep`` (e.g. renamed ones).

    Example::

        prune(Path("imports/ycb_gso"), manifest, {"ycb_025_mug"})
    """
    gone = sorted(set(man["objects"]) - keep)
    for n in gone:
        e = man["objects"].pop(n)
        for rel in (e.get("card"), e.get("material")):
            if rel and (root / rel).is_file():
                (root / rel).unlink()
        shutil.rmtree(root / mf.MESH_DIR / n, ignore_errors=True)
    qu.drop(root / "queue.jsonl", [(n, "material.density") for n in gone])
    checks = root / "checks.json"
    if gone and checks.is_file():
        data = json.loads(checks.read_text(encoding="utf-8"))
        checks.write_text(json.dumps({k: v for k, v in data.items() if k not in gone}, indent=1) + "\n",
                          encoding="utf-8")
    return gone


def build(out_dirs: list[Path], root: Path, workers: int = 3, sources: Path | None = None,
          prune_missing: bool = False) -> dict:
    """Build (or refresh) the import library at ``root`` from batch outputs; returns a JSON summary.

    Sourcing records (``alloy.sourcing.load_records``, from ``sources`` or ``<alloy-assets>/sources/imports``) are
    written over the estimates; a record whose mass is DOC, SNIPPET or UNVERIFIED retires the object's queue row.
    ``prune_missing``: drop objects the outputs no longer produce (pass every output folder).

    Example::

        build([Path("jobs/az/ycb_0/out")], Path("alloy-assets/imports/ycb_gso"))
    """
    root = Path(root)
    lib = CardLibrary()
    man = mf.load(root / "manifest.json", LIB)
    from alloy.sourcing import load_records  # noqa: PLC0415

    records = load_records(LIB, sources)
    rows: list = []
    specs = object_specs(collect_results(out_dirs))
    cached = {n: e["physics"] for n, e in man["objects"].items()}
    walls = wall_records([(s.name, r["files"][PHYSICS], d) for s, r, d in specs], cached, workers)
    for spec, result, d in specs:
        rec = records.get(spec.name)
        man["objects"][spec.name] = write_object(root, spec, result, d, lib, walls[spec.name], rec)
        rows += [r for r in spec.queue if mass_tag(rec) not in STRONG_TAGS]
    pruned = prune(root, man, {s.name for s, _, _ in specs}) if prune_missing else []
    thumbs = apply_thumbs(root, man)
    mf.save(root / "manifest.json", man)
    qu.add(root / "queue.jsonl", rows)
    retired = [(n, "material.density") for n, e in man["objects"].items() if e["physics"]["mass_status"] == "sourced"]
    qlen = qu.drop(root / "queue.jsonl", retired)
    (root / "ATTRIBUTION.md").write_text(_attribution(man["objects"]), encoding="utf-8")
    (root / ".gitignore").write_text(GIT_IGNORE, encoding="utf-8")
    status = [e["physics"]["mass_status"] for e in man["objects"].values()]
    rejected = sorted(n for n in records if n in man["objects"] and man["objects"][n].get("sourcing") is None)
    partial = sorted(n for n, e in man["objects"].items() if e.get("sourcing") == "mass only")
    return {"objects": len(man["objects"]), "measured": status.count("measured"), "sourced": status.count("sourced"),
            "estimated": status.count("estimate"), "records": len(records), "records_rejected": rejected,
            "records_mass_only": partial, "pruned": pruned, "thumbs_from_thumbs_json": thumbs, "queue": qlen}
