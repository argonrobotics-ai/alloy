"""Alloy cards for imported RoboCasa assets: object cards (with a provenance header) and new material cards.

The import root is a card library root: ``objects/<category>/<name>.yaml``, ``materials/robocasa_*.yaml`` and the
models under ``mjcf/``. Load it with ``CardLibrary([default_root(), <import root>])``.

Example::

    >>> from alloy.importers.robocasa.cards_out import object_card
    >>> card = object_card("glass_cup/GlassCup003", "glass_soda_lime", motion="dynamic")
    >>> card.shape.path, card.shape.body
    ('mjcf/glass_cup/robocasa_glass_cup_003/model.xml', 'robocasa_glass_cup_003')
"""

from __future__ import annotations

from pathlib import Path

from alloy.cards import dump_card
from alloy.cards import types as ct
from alloy.importers.robocasa import naming
from alloy.importers.robocasa.materials import MaterialTable
from alloy.importers.robocasa.packs import Pack


def object_card(asset: str, surface: str, motion: str = "dynamic") -> ct.ObjectCard:
    """The card of an imported asset: its MJCF model, surface material and motion."""
    name = naming.card_name(asset)
    return ct.ObjectCard(name=name, shape=ct.MJCFSource(path=naming.model_rel(asset), body=name), material=surface,
                         motion=motion)


def provenance_header(asset: str, pack: Pack, lines: list[str]) -> str:
    """YAML comment block: source, licence, attribution and the importer's notes (mass, flags)."""
    out = [f"RoboCasa asset {pack.key}/{pack.top}/{asset} (source: {pack.source_url}).",
           f"Licence: {pack.licence}. Attribution: {pack.attribution}.",
           "Generated by alloy.importers.robocasa; do not edit by hand (re-run the importer)."]
    out += lines
    return "".join(f"# {line}\n" for line in out)


def write_object_card(root: Path, asset: str, card: ct.ObjectCard, header: str) -> Path:
    """Write the card under ``root`` and return its path."""
    path = root / naming.card_rel(asset)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + dump_card(card))
    return path


def write_material_cards(root: Path, table: MaterialTable, names: set[str]) -> list[Path]:
    """Write the new ``robocasa_*`` surface materials among ``names`` (library materials need no file)."""
    out = []
    for name in sorted(n for n in names if n in table.cards):
        path = root / "materials" / f"{name}.yaml"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("# New material for RoboCasa imports (alloy/importers/robocasa/data/materials.yaml).\n"
                        + dump_card(table.cards[name]))
        out.append(path)
    return out


__all__ = ["object_card", "provenance_header", "write_material_cards", "write_object_card"]
