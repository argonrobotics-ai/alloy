"""RoboCasa asset packs and the licence decision for each (keep, drop or hold).

RoboCasa (https://robocasa.ai, code MIT) states "Assets and Datasets: CC BY 4.0", but its packs come from different
places, so each pack is decided on its own:

- ``objects_lightwheel`` and ``fixtures_lightwheel``: Lightwheel-made objects and articulated fixtures, published by
  NVIDIA as the Hugging Face dataset ``nvidia/PhysicalAI-Robotics-Manipulation-Objects-Kitchen-MJCF`` under
  CC BY 4.0 (the packs' README.md points there). **Kept.**
- ``objaverse``: objects re-exported from Objaverse. Objaverse objects carry their own licences (CC BY, but also
  CC BY-NC, CC BY-NC-SA, CC BY-SA), and the pack keeps no Objaverse IDs (names like ``alcohol_1``, trimesh exports),
  so no object's licence can be checked. **Dropped** (unclear; the licence-filtered Objaverse importer covers it).
- ``aigen_objs``: text-to-3D objects generated by the RoboCasa team. RoboCasa grants CC BY 4.0, but the generator's
  terms for commercial use depend on the account tier used, which is not recorded. **Held** until a person decides.
- ``fixtures`` (accessories: knife blocks, outlets, switches, paper-towel holders): no per-asset source given.
  **Held** (the Lightwheel pack has knife blocks and paper-towel holders under a clear licence).

Example::

    >>> from alloy.importers.robocasa.packs import PACKS, kept_packs
    >>> [p.key for p in kept_packs()]
    ['objects_lightwheel', 'fixtures_lightwheel']
    >>> PACKS["objaverse"].decision
    'drop'
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

Decision = Literal["keep", "drop", "hold"]
Kind = Literal["object", "fixture"]

LIGHTWHEEL_DATASET = "https://huggingface.co/datasets/nvidia/PhysicalAI-Robotics-Manipulation-Objects-Kitchen-MJCF"
ROBOCASA_URL = "https://github.com/robocasa/robocasa"
BOX_BASE = "https://utexas.box.com/shared/static"


@dataclass(frozen=True)
class Pack:
    """One RoboCasa download pack (a zip) and what the importer does with it."""

    key: str                    # RoboCasa's box_links_assets.json key
    box_id: str                 # Box shared-link id (the zip is BOX_BASE/<id>.zip)
    top: str                    # top folder inside the zip
    kind: Kind
    licence: str                # SPDX-style id, or "unclear"
    decision: Decision
    reason: str
    attribution: str = ""       # text every derived card carries
    source_url: str = ROBOCASA_URL

    @property
    def url(self) -> str:
        """Direct-download URL of the pack zip."""
        return f"{BOX_BASE}/{self.box_id}.zip"


_LW_ATTR = ("Lightwheel kitchen assets from NVIDIA PhysicalAI-Robotics-Manipulation-Objects-Kitchen-MJCF "
            "(CC BY 4.0), as packaged by RoboCasa; converted for Alloy (collision hulls, mass and materials changed)")

PACKS: dict[str, Pack] = {p.key: p for p in (
    Pack("objects_lightwheel", "vckqvvkh1z8t69k8qcpcmee6k66stii4", "lightwheel", "object", "CC-BY-4.0", "keep",
         "NVIDIA dataset card licence: cc-by-4.0; pack README points to it", _LW_ATTR, LIGHTWHEEL_DATASET),
    Pack("fixtures_lightwheel", "idbncsadpnaz1jfl4i6m8qejawk7p9pi", "fixtures", "fixture", "CC-BY-4.0", "keep",
         "NVIDIA dataset card licence: cc-by-4.0; pack README points to it", _LW_ATTR, LIGHTWHEEL_DATASET),
    Pack("objaverse", "03eionyo8fk3a9dsksq9jb8du5lqfw8h", "objaverse", "object", "unclear", "drop",
         "per-object Objaverse licences (some NC/SA) and no Objaverse IDs in the pack, so none can be checked"),
    Pack("aigen_objs", "nwi1vrn5pgbo95kushkasa3nx1i012ff", "aigen_objs", "object", "CC-BY-4.0", "hold",
         "text-to-3D outputs; the generator's commercial terms depend on an unrecorded account tier"),
    Pack("fixtures", "zt9vbo38yb9f1alw9iuahck55hoa65y6", "fixtures", "fixture", "unclear", "hold",
         "accessory meshes with no per-asset source"),
)}


def kept_packs() -> list[Pack]:
    """Packs whose licence is clear and allowed (CC0, CC BY, MIT, Apache-2.0, BSD).

    Example::

        >>> [p.licence for p in kept_packs()]
        ['CC-BY-4.0', 'CC-BY-4.0']
    """
    return [p for p in PACKS.values() if p.decision == "keep"]


def pack(key: str) -> Pack:
    """The pack named ``key``; ``KeyError`` lists the valid keys.

    Example::

        >>> pack("objects_lightwheel").kind
        'object'
    """
    try:
        return PACKS[key]
    except KeyError:
        raise KeyError(f"unknown RoboCasa pack {key!r}; use one of {sorted(PACKS)}") from None


def require_kept(key: str) -> Pack:
    """The pack, or ``PermissionError`` saying why it may not be imported.

    Example::

        >>> require_kept("objects_lightwheel").decision
        'keep'
    """
    p = pack(key)
    if p.decision != "keep":
        raise PermissionError(f"RoboCasa pack {key!r} is {p.decision!r}: {p.reason}. Import a kept pack instead: "
                              f"{[k.key for k in kept_packs()]}")
    return p


__all__ = ["PACKS", "Pack", "kept_packs", "pack", "require_kept"]
