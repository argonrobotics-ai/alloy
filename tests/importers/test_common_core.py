def test_material_card_applies_a_sourcing_record():
    sourcing = pytest.importorskip("alloy.sourcing")
    base = CardLibrary().material("pp_homopolymer")
    mu = sourcing.SourcedValue(field="mu_static", value=0.45, lo=0.35, hi=0.55, tag="ESTIMATE", reason="test prior")
    mass = sourcing.SourcedValue(field="mass", value=0.05, lo=0.04, hi=0.06, tag="ESTIMATE", reason="test range")
    rec = sourcing.ObjectRecord(library="imp", object="imp_test_mug", values={"mu_static": mu, "mass": mass})
    est = cw.material_card(_spec("density"), base, rec)          # an estimate takes the record's mass
    assert est.density.value == pytest.approx(0.05 / 1.378e-4)
    assert est.surface.mu_static.value == 0.45
    fit = cw.material_card(_spec("mass"), base, rec)             # a measured mass keeps its fit density
    assert fit.density.source == "fit" and fit.surface.mu_static.value == 0.45
    huge = sourcing.ObjectRecord(library="imp", object="imp_test_mug", values={"mass": sourcing.SourcedValue(
        field="mass", value=50.0, lo=40.0, hi=60.0, tag="ESTIMATE", reason="wrong object")})
    with pytest.raises(sourcing.SourcingError):
        cw.material_card(_spec("density"), base, huge)


def test_drop_verdict_fails_wrong_mass_and_restless_bodies():
    from alloy.importers.common import droptest as dt  # noqa: PLC0415

    steps, step = 2000, 1.25e-3
    rest = np.zeros((steps, 3))
    rest[:, 2] = 0.05
    lows = np.zeros(steps)
    assert dt._verdict(rest, lows, step)[:2] == (True, "ok")
    moving = rest.copy()
    moving[:, 0] = np.arange(steps) * step * 1.0                     # sliding away at 1 m/s
    assert "still moving" in dt._verdict(moving, lows, step)[1]
    bouncing = rest.copy()
    bouncing[-200:, 2] -= 0.08 * np.abs(np.sin(np.linspace(0, 6, 200)))      # 8 cm hops, start height not exceeded
    bouncing[-1] = bouncing[-2]
    assert "bouncing" in dt._verdict(bouncing, lows, step)[1]
    assert dt.mass_issue(0.5 * (1 + 1e-6), 0.5) is None
    assert "centre the mesh" in dt.mass_issue(953.0, 0.5)
    assert dt.mass_issue(float("nan"), 0.5) is not None
