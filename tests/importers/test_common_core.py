def test_queue_replace_and_drop(tmp_path):
    p = tmp_path / "queue.jsonl"
    row = qu.QueueRow("c", "material.density", 1.0, (0.5, 2.0), "ESTIMATE: x", "cat", "q", {"gtin": "1"})
    assert qu.add(p, [row]) == 1
    assert qu.add(p, [qu.QueueRow("c", "material.density", 2.0, None, "ESTIMATE: y", "cat", "q")]) == 1
    assert json.loads(p.read_text())["value"] == 2.0
    assert qu.drop(p, [("c", "material.density")]) == 0


def test_extract_skips_traversal_and_links(tmp_path):
    z = tmp_path / "a.zip"
    with zipfile.ZipFile(z, "w") as zf:
        zf.writestr("meshes/model.obj", "v 0 0 0\n")
        zf.writestr("../evil.txt", "x")
    assert is_archive(z)
    (tmp_path / "bare.glb").write_bytes(b"glTF\x02\x00\x00\x00" + bytes(64))
    assert not is_archive(tmp_path / "bare.glb")
    assert extract(z, tmp_path / "out", ("meshes",)) == 1
    assert not (tmp_path / "evil.txt").exists()
    t = tmp_path / "a.tgz"
    with tarfile.open(t, "w:gz") as tf:
        info = tarfile.TarInfo("obj/link")
        info.type, info.linkname = tarfile.SYMTYPE, "/etc/passwd"
        tf.addfile(info)
        data = b"v 0 0 0\n"
        info = tarfile.TarInfo("obj/model.obj")
        info.size = len(data)
        tf.addfile(info, io.BytesIO(data))
    assert extract(t, tmp_path / "out2", ("obj",)) == 1
    assert not (tmp_path / "out2" / "obj" / "link").exists()
    with pytest.raises(ImporterError, match="member paths"):
        extract(t, tmp_path / "out3", ("nothing",))


