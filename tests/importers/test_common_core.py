def test_mesh_text_is_deterministic():
    a = mesh_obj_text(CUBE_V, CUBE_F, "h")
    assert a == mesh_obj_text(CUBE_V.copy(), CUBE_F.copy(), "h")
    assert sha256_bytes(a.encode()) == sha256_bytes(a.encode())


def test_clean_cube_and_pinch_repair():
    assert is_clean(CUBE_F)
    # two cubes sharing one edge (vertices 1-3 of cube A = vertices 4-6 of cube B shifted): a pinched edge
    v2 = np.concatenate([CUBE_V, CUBE_V + [1.0, 1.0, 0.0]])
    shared = {8 + 0: 6, 8 + 1: 7}                     # cube B's (0,0,0),(0,0,1) = cube A's (1,1,0),(1,1,1)
    f2 = np.concatenate([CUBE_F, np.vectorize(lambda i: shared.get(i + 8, i + 8))(CUBE_F)])
    _, counts = edge_counts(f2)
    assert (counts > 2).any()
    v, f, ok = fix_pinches(v2, f2)
    assert ok and is_clean(f)


def _spec(kind: str = "mass") -> cw.CardSpec:
    mass = (cw.MassSpec("mass", 0.118, (0.117, 0.119), "118 g measured, test")
            if kind == "mass" else cw.MassSpec("density", 300.0, (150.0, 500.0), "test estimate"))
    return cw.CardSpec("imp_test_mug", "pp_homopolymer", "test", mass, 1.378e-4, "meshes/imp_test_mug/physics.obj",
                       "0" * 64, 12, "generated by a test")


def test_effective_material_fit_and_estimate():
    base = CardLibrary().material("pp_homopolymer")
    fit = cw.effective_material(_spec("mass"), base)
    assert fit.density.source == "fit"
    assert fit.density.value == pytest.approx(0.118 / 1.378e-4)
    lo, hi = fit.density.unc
    assert lo < fit.density.value < hi
    assert fit.surface.mu_dynamic.value == base.surface.mu_dynamic.value
    assert "pp_homopolymer" in fit.surface.mu_dynamic.note
    est = cw.effective_material(_spec("density"), base)
    assert est.density.source == "model" and est.density.note.startswith("ESTIMATE")


def test_card_texts_round_trip():
    base = CardLibrary().material("pp_homopolymer")
    obj_yaml, mat_yaml = cw.card_texts(_spec(), base)
    obj = loads_card(obj_yaml, ct.ObjectCard)
    assert obj.shape.collision == "decompose" and obj.shape.max_parts == 12
    assert obj.material == "imp_test_mug_eff"
    assert loads_card(mat_yaml, ct.MaterialCard).name == "imp_test_mug_eff"
    assert obj_yaml.startswith("# generated by a test")


def test_manifest_fetch_from_a_directory_store(tmp_path):
    store = tmp_path / "store"
    (store / "lib" / "meshes" / "a").mkdir(parents=True)
    f = store / "lib" / "meshes" / "a" / "physics.obj"
    f.write_text("v 0 0 0\n")
    man = mf.empty("lib")
    man["objects"]["a"] = {"files": {"physics.obj": mf.file_entry(f)}}
    root = tmp_path / "root"
    assert mf.missing_files(root, man) == [("a", "physics.obj")]
    assert mf.fetch(root, man, store=str(store))["fetched"] == 1
    assert mf.missing_files(root, man) == []
    mf.save(root / "manifest.json", man)
    assert mf.load(root / "manifest.json", "lib")["objects"]["a"]["files"]["physics.obj"]["bytes"] == 8


